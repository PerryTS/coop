#[derive(Debug, thiserror::Error)]
pub enum InvocationError {
    #[error("deployment {0:?} has no live runtime")]
    Unavailable(String),
    #[error("deployment {deployment:?} invocation limit is full ({limit})")]
    Overloaded { deployment: String, limit: usize },
    #[error(
        "deployment {deployment:?} {entrypoint} invocation exceeded its {max_wall_clock_ms} ms wall-clock limit"
    )]
    DeadlineExceeded {
        deployment: String,
        entrypoint: &'static str,
        max_wall_clock_ms: u32,
    },
    #[error("deployment {deployment:?} request {field} exceeds {limit} bytes")]
    RequestTooLarge {
        deployment: String,
        field: &'static str,
        limit: usize,
    },
    #[error("deployment {deployment:?} response {field} exceeds {limit} bytes")]
    ResponseTooLarge {
        deployment: String,
        field: &'static str,
        limit: usize,
    },
    #[error(transparent)]
    Runtime(#[from] anyhow::Error),
}

struct InvocationAdmission {
    deployment: String,
    permits: Arc<Semaphore>,
    max_concurrent: usize,
    max_wall_clock_ms: u32,
    max_request_body_bytes: usize,
    max_request_header_bytes: usize,
    max_response_body_bytes: usize,
    max_response_header_bytes: usize,
    max_queue_payload_bytes: usize,
    active: AtomicUsize,
    in_flight_metric: metrics::Gauge,
}

impl InvocationAdmission {
    fn new(
        deployment: &str,
        limits: &crate::config::DeploymentLimitsConfig,
        command_queue_capacity: usize,
    ) -> Self {
        // A thread-affine host can retain at most the configured number in its
        // executor queue. Cap admission at that exact number: assuming an
        // executor has already dequeued one command would leave a race where a
        // burst fills the channel before the thread begins receiving.
        let structural_limit = command_queue_capacity.max(1);
        let configured_limit = limits.max_concurrent_invocations as usize;
        let max_concurrent = configured_limit.min(structural_limit).max(1);
        info!(
            deployment,
            configured_limit,
            structural_limit,
            effective_limit = max_concurrent,
            max_wall_clock_ms = limits.max_wall_clock_ms,
            "deployment invocation admission configured"
        );
        let in_flight_metric = metrics::gauge!(
            "coop_invocations_in_flight",
            "deployment" => deployment.to_string()
        );
        in_flight_metric.set(0.0);
        Self {
            deployment: deployment.to_string(),
            permits: Arc::new(Semaphore::new(max_concurrent)),
            max_concurrent,
            max_wall_clock_ms: limits.max_wall_clock_ms,
            max_request_body_bytes: limits.max_request_body_bytes,
            max_request_header_bytes: limits.max_request_header_bytes,
            max_response_body_bytes: limits.max_response_body_bytes,
            max_response_header_bytes: limits.max_response_header_bytes,
            max_queue_payload_bytes: limits.max_queue_payload_bytes,
            active: AtomicUsize::new(0),
            in_flight_metric,
        }
    }

    fn validate_http_request(&self, request: &HttpDispatchRequest) -> Result<(), InvocationError> {
        if request.body.len() > self.max_request_body_bytes {
            crate::metrics::record_invocation_rejected(&self.deployment, "http", "request_body");
            return Err(InvocationError::RequestTooLarge {
                deployment: self.deployment.clone(),
                field: "body",
                limit: self.max_request_body_bytes,
            });
        }
        if header_bytes(&request.headers) > self.max_request_header_bytes {
            crate::metrics::record_invocation_rejected(&self.deployment, "http", "request_headers");
            return Err(InvocationError::RequestTooLarge {
                deployment: self.deployment.clone(),
                field: "headers",
                limit: self.max_request_header_bytes,
            });
        }
        if coop_host_abi::http_request_frame_len(request).is_err() {
            crate::metrics::record_invocation_rejected(&self.deployment, "http", "request_frame");
            return Err(InvocationError::RequestTooLarge {
                deployment: self.deployment.clone(),
                field: "ABI frame",
                limit: coop_host_abi::MAX_FRAME_SIZE,
            });
        }
        Ok(())
    }

    fn validate_http_response(
        &self,
        response: &HttpDispatchResponse,
    ) -> Result<(), InvocationError> {
        if response.body.len() > self.max_response_body_bytes {
            crate::metrics::record_invocation_rejected(&self.deployment, "http", "response_body");
            return Err(InvocationError::ResponseTooLarge {
                deployment: self.deployment.clone(),
                field: "body",
                limit: self.max_response_body_bytes,
            });
        }
        if header_bytes(&response.headers) > self.max_response_header_bytes {
            crate::metrics::record_invocation_rejected(
                &self.deployment,
                "http",
                "response_headers",
            );
            return Err(InvocationError::ResponseTooLarge {
                deployment: self.deployment.clone(),
                field: "headers",
                limit: self.max_response_header_bytes,
            });
        }
        if coop_host_abi::http_response_frame_len(response).is_err() {
            crate::metrics::record_invocation_rejected(&self.deployment, "http", "response_frame");
            return Err(InvocationError::ResponseTooLarge {
                deployment: self.deployment.clone(),
                field: "ABI frame",
                limit: coop_host_abi::MAX_FRAME_SIZE,
            });
        }
        Ok(())
    }

    fn validate_queue_message(
        &self,
        message: &coop_host_abi::QueueDispatchMessage,
    ) -> Result<(), InvocationError> {
        if message.payload.len() > self.max_queue_payload_bytes {
            crate::metrics::record_invocation_rejected(&self.deployment, "queue", "payload");
            return Err(InvocationError::RequestTooLarge {
                deployment: self.deployment.clone(),
                field: "queue payload",
                limit: self.max_queue_payload_bytes,
            });
        }
        Ok(())
    }

    async fn invoke<T, F>(
        self: &Arc<Self>,
        entrypoint: &'static str,
        future: F,
    ) -> Result<T, InvocationError>
    where
        T: Send + 'static,
        F: Future<Output = Result<T>> + Send + 'static,
    {
        let guard = self.try_admit(entrypoint, true)?;
        self.invoke_admitted(entrypoint, guard, future).await
    }

    fn try_admit(
        self: &Arc<Self>,
        entrypoint: &'static str,
        record_rejection: bool,
    ) -> Result<InvocationPermit, InvocationError> {
        let permit = match self.permits.clone().try_acquire_owned() {
            Ok(permit) => permit,
            Err(_) => {
                if record_rejection {
                    crate::metrics::record_invocation_rejected(
                        &self.deployment,
                        entrypoint,
                        "concurrency",
                    );
                }
                return Err(InvocationError::Overloaded {
                    deployment: self.deployment.clone(),
                    limit: self.max_concurrent,
                });
            }
        };
        let active = self.active.fetch_add(1, Ordering::AcqRel) + 1;
        self.in_flight_metric.set(active as f64);
        let guard = InvocationPermit {
            admission: self.clone(),
            _permit: permit,
        };
        Ok(guard)
    }

    async fn invoke_admitted<T, F>(
        self: &Arc<Self>,
        entrypoint: &'static str,
        guard: InvocationPermit,
        future: F,
    ) -> Result<T, InvocationError>
    where
        T: Send + 'static,
        F: Future<Output = Result<T>> + Send + 'static,
    {
        let mut future = Box::pin(future);
        match tokio::time::timeout(
            Duration::from_millis(u64::from(self.max_wall_clock_ms)),
            &mut future,
        )
        .await
        {
            Ok(result) => {
                drop(guard);
                result.map_err(InvocationError::Runtime)
            }
            Err(_) => {
                crate::metrics::record_invocation_timeout(&self.deployment, entrypoint);
                // The caller receives its deadline immediately, but a native
                // in-process call cannot be cancelled safely. Keep the
                // admission permit attached to the actual work so timeouts do
                // not silently exceed the configured concurrency ceiling.
                tokio::spawn(async move {
                    let _guard = guard;
                    let _ = future.await;
                });
                Err(InvocationError::DeadlineExceeded {
                    deployment: self.deployment.clone(),
                    entrypoint,
                    max_wall_clock_ms: self.max_wall_clock_ms,
                })
            }
        }
    }
}

struct InvocationPermit {
    // Drop the semaphore permit only after updating the active gauge.
    admission: Arc<InvocationAdmission>,
    _permit: OwnedSemaphorePermit,
}

impl Drop for InvocationPermit {
    fn drop(&mut self) {
        let active = self.admission.active.fetch_sub(1, Ordering::AcqRel) - 1;
        self.admission.in_flight_metric.set(active as f64);
    }
}

fn header_bytes(headers: &[(String, String)]) -> usize {
    headers.iter().fold(0usize, |total, (name, value)| {
        total.saturating_add(name.len()).saturating_add(value.len())
    })
}

fn current_unix_time_ms() -> u128 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis()
}

/// Returns true when cancellation won over the delay.
async fn wait_or_stop(stop: &CancellationToken, delay: Duration) -> bool {
    tokio::select! {
        biased;
        _ = stop.cancelled() => true,
        _ = tokio::time::sleep(delay) => false,
    }
}

fn queue_store_error_backoff(poll_interval: Duration, consecutive_errors: u32) -> Duration {
    const MIN_BACKOFF: Duration = Duration::from_millis(250);
    const MAX_BACKOFF: Duration = Duration::from_secs(5);
    let exponent = consecutive_errors.saturating_sub(1).min(5);
    poll_interval
        .max(MIN_BACKOFF)
        .saturating_mul(1_u32 << exponent)
        .min(MAX_BACKOFF)
}

