impl Drop for CompilePhaseMetric {
    fn drop(&mut self) {
        let elapsed_secs = self.started.elapsed().as_secs_f64();
        crate::metrics::record_compile_phase(
            &self.deployment,
            self.phase,
            self.outcome,
            elapsed_secs,
        );
        info!(
            deployment = %self.deployment,
            phase = self.phase,
            outcome = self.outcome,
            elapsed_ms = elapsed_secs * 1_000.0,
            "application build phase complete"
        );
    }
}

