    async fn collect_deployment_artifacts(&self, deployment: &str) -> Result<()> {
        let pins = {
            let live = self.live.read().await;
            live.get(deployment)
                .and_then(|live| {
                    self.artifact_store
                        .package_id_for_library(deployment, &live.dylib_path)
                })
                .into_iter()
                .collect::<HashSet<_>>()
        };
        let store = self.artifact_store.clone();
        let status_store = store.clone();
        let deployment = deployment.to_string();
        let task_deployment = deployment.clone();
        let removed =
            match tokio::task::spawn_blocking(move || store.collect(&task_deployment, &pins))
                .await
                .context("joining artifact collection task")
            {
                Ok(Ok(removed)) => removed,
                Ok(Err(error)) => {
                    crate::metrics::record_artifact_collection(&deployment, "failure", 0);
                    return Err(error);
                }
                Err(error) => {
                    crate::metrics::record_artifact_collection(&deployment, "failure", 0);
                    return Err(error);
                }
            };
        let status = tokio::task::spawn_blocking({
            let deployment = deployment.clone();
            move || status_store.status(&deployment)
        })
        .await
        .context("joining post-collection artifact-status task")??;
        crate::metrics::record_artifact_collection(&deployment, "success", removed.len());
        crate::metrics::set_artifact_inventory(
            &deployment,
            status.packages.len(),
            status.retained_bytes,
        );
        Ok(())
    }

    async fn start_runtime(
        &self,
        name: &str,
        dylib_path: &Path,
        module_name: Option<&str>,
        deployment_context_id: u64,
        config: &DeploymentConfig,
        execution_mode: ExecutionMode,
    ) -> Result<LiveRuntime> {
        if execution_mode == ExecutionMode::InProcess {
            info!(
                deployment = name,
                dylib = %dylib_path.display(),
                requested_isolation = config.isolation.class.requested_label(),
                effective_isolation = config
                    .isolation
                    .class
                    .effective_label(self.runtime_cfg.execution.mode),
                "preloading application library in daemon"
            );
            let deployment = name.to_owned();
            let path = dylib_path.to_owned();
            let module = module_name.map(str::to_owned);
            let options = DeploymentHostOptions {
                executor_stack_size_bytes: self.runtime_cfg.execution.executor_stack_size_bytes,
                command_queue_capacity: self.runtime_cfg.execution.command_queue_capacity,
                gc_reclaim_check_interval: self.runtime_cfg.execution.gc_reclaim_check_interval,
                gc_reclaim_growth_bytes: self.runtime_cfg.execution.gc_reclaim_growth_bytes,
                deployment_context_id,
            };
            let host = tokio::task::spawn_blocking(move || {
                DeploymentHost::load_with_options(&deployment, &path, module.as_deref(), options)
                    .with_context(|| format!("preloading deployment {deployment}"))
            })
            .await
            .with_context(|| format!("joining preload task for deployment {name}"))??;
            return Ok(LiveRuntime::InProcess {
                host: Arc::new(host),
            });
        }

        if execution_mode == ExecutionMode::Shard {
            return self
                .start_shard_runtime(name, dylib_path, module_name, deployment_context_id, config)
                .await;
        }

        std::fs::create_dir_all(&self.runtime_cfg.paths.sockets_dir).with_context(|| {
            format!(
                "creating sockets dir {:?}",
                self.runtime_cfg.paths.sockets_dir
            )
        })?;
        let worker_generation = WORKER_SOCKET_SEQUENCE.fetch_add(1, Ordering::Relaxed);
        let socket_path = self.runtime_cfg.paths.sockets_dir.join(format!(
            "{name}-{}-{worker_generation}.sock",
            std::process::id()
        ));

        let worker_cgroup = WorkerCgroup::prepare(
            &self.runtime_cfg.execution.cgroup,
            name,
            worker_generation,
            &config.limits,
        )
        .with_context(|| format!("preparing cgroup for dedicated worker {name}"))?;

        let worker_binary = self.locate_worker_binary()?;
        info!(
            deployment = name,
            dylib = %dylib_path.display(),
            socket = %socket_path.display(),
            worker = %worker_binary.display(),
            requested_isolation = config.isolation.class.requested_label(),
            effective_isolation = config
                .isolation
                .class
                .effective_label(self.runtime_cfg.execution.mode),
            cgroup = ?worker_cgroup.as_ref().map(|cgroup| cgroup.path()),
            "spawning isolated coop-worker"
        );

        let mut cmd = tokio::process::Command::new(&worker_binary);
        cmd.arg("--deployment")
            .arg(name)
            .arg("--dylib")
            .arg(dylib_path)
            .arg("--socket")
            .arg(&socket_path)
            .arg("--sockets-dir")
            .arg(&self.runtime_cfg.paths.sockets_dir)
            .arg("--perry-runtime")
            .arg(&self.runtime_cfg.paths.perry_runtime_library)
            .arg("--perry-stdlib")
            .arg(&self.runtime_cfg.paths.perry_stdlib_library)
            .arg("--provider-verification")
            .arg(self.runtime_cfg.execution.provider_verification.as_str())
            .arg("--parent-pid")
            .arg(std::process::id().to_string())
            .arg("--executor-stack-size-bytes")
            .arg(
                self.runtime_cfg
                    .execution
                    .executor_stack_size_bytes
                    .to_string(),
            )
            .arg("--command-queue-capacity")
            .arg(
                self.runtime_cfg
                    .execution
                    .command_queue_capacity
                    .to_string(),
            )
            .arg("--gc-reclaim-check-interval")
            .arg(
                self.runtime_cfg
                    .execution
                    .gc_reclaim_check_interval
                    .to_string(),
            )
            .arg("--gc-reclaim-growth-bytes")
            .arg(
                self.runtime_cfg
                    .execution
                    .gc_reclaim_growth_bytes
                    .to_string(),
            )
            .arg("--deployment-context-id")
            .arg(deployment_context_id.to_string());
        if let Some(postgres) = &self.runtime_cfg.postgres {
            cmd.env("COOP_QUEUE_POSTGRES_URL", &postgres.url)
                .env(
                    "COOP_QUEUE_POSTGRES_MAX_CONNECTIONS",
                    postgres.max_connections.min(2).max(1).to_string(),
                )
                .env(
                    "COOP_QUEUE_POLICIES_JSON",
                    serde_json::to_string(&WorkerQueuePolicies::from_config(config))?,
                );
        }
        // `kv` and `storage` are scoped by the worker's own process
        // environment, which is why they are only offered to a dedicated
        // worker: one process, one deployment. Both are passed through the
        // environment rather than argv so a Redis password stays out of the
        // process table. The worker derives the deployment's key prefix and
        // storage subdirectory itself; it is never told another deployment's.
        if let Some(redis) = &self.runtime_cfg.redis {
            cmd.env("COOP_REDIS_URL", &redis.url);
        }
        cmd.env("COOP_STORAGE_ROOT", &self.runtime_cfg.paths.storage_dir);
        if let Some(module_name) = module_name {
            cmd.arg("--module-name").arg(module_name);
        }
        if let Some(cgroup) = worker_cgroup.as_ref() {
            cmd.arg("--cgroup-procs").arg(cgroup.procs_path());
        }

        let mut child = cmd
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .kill_on_drop(true)
            .spawn()
            .with_context(|| format!("spawning {:?}", worker_binary))?;

        if let Some(stdout) = child.stdout.take() {
            let deployment_name = name.to_string();
            tokio::spawn(async move {
                let mut reader = tokio::io::BufReader::new(stdout);
                let mut line = String::new();
                use tokio::io::AsyncBufReadExt;
                loop {
                    line.clear();
                    match reader.read_line(&mut line).await {
                        Ok(0) => break,
                        Ok(_) => info!(
                            target: "worker.stdout",
                            deployment = %deployment_name,
                            "{}",
                            line.trim_end()
                        ),
                        Err(error) => {
                            warn!(deployment = %deployment_name, ?error, "reading worker stdout");
                            break;
                        }
                    }
                }
            });
        }
        if let Some(stderr) = child.stderr.take() {
            let deployment_name = name.to_string();
            tokio::spawn(async move {
                let mut reader = tokio::io::BufReader::new(stderr);
                let mut line = String::new();
                use tokio::io::AsyncBufReadExt;
                loop {
                    line.clear();
                    match reader.read_line(&mut line).await {
                        Ok(0) => break,
                        Ok(_) => warn!(
                            target: "worker.stderr",
                            deployment = %deployment_name,
                            "{}",
                            line.trim_end()
                        ),
                        Err(_) => break,
                    }
                }
            });
        }

        let connect_deadline = std::time::Instant::now() + Duration::from_secs(5);
        let client_result: Result<Arc<WorkerClient>> = async {
            loop {
                if let Some(status) = child
                    .try_wait()
                    .with_context(|| format!("checking worker {name} startup status"))?
                {
                    return Err(anyhow!(
                        "worker for deployment {name} exited before handshake ({status})"
                    ));
                }
                let connect_error = match WorkerClient::connect(name, &socket_path).await {
                    Ok(client) => break Ok(Arc::new(client)),
                    Err(error) => error,
                };
                if std::time::Instant::now() >= connect_deadline {
                    break Err(connect_error).with_context(|| {
                        format!(
                            "timed out connecting to worker socket {:?} for deployment {name}",
                            socket_path
                        )
                    });
                }
                tokio::time::sleep(Duration::from_millis(10)).await;
            }
        }
        .await;
        let client = match client_result {
            Ok(client) => client,
            Err(error) => {
                let _ = child.kill().await;
                let _ = child.wait().await;
                let _ = std::fs::remove_file(&socket_path);
                return Err(error);
            }
        };
        let pid = child.id().unwrap_or(0);
        Ok(LiveRuntime::Worker {
            socket_path,
            child,
            pid,
            client,
            cgroup: worker_cgroup,
        })
    }

    fn shard_slot(deployment: &str, count: usize) -> usize {
        debug_assert!(count > 0);
        let digest = Sha256::digest(deployment.as_bytes());
        let mut prefix = [0_u8; 8];
        prefix.copy_from_slice(&digest[..8]);
        (u64::from_be_bytes(prefix) % count as u64) as usize
    }

    fn shard_candidate_slots(
        deployment: &str,
        count: usize,
        existing_slot: Option<usize>,
    ) -> Vec<usize> {
        debug_assert!(count > 0);
        let preferred_slot = Self::shard_slot(deployment, count);
        let mut candidate_slots = Vec::with_capacity(count);
        if let Some(slot) = existing_slot.filter(|slot| *slot < count) {
            candidate_slots.push(slot);
        }
        for offset in 0..count {
            let slot = (preferred_slot + offset) % count;
            if !candidate_slots.contains(&slot) {
                candidate_slots.push(slot);
            }
        }
        candidate_slots
    }

    async fn start_shard_runtime(
        &self,
        name: &str,
        dylib_path: &Path,
        module_name: Option<&str>,
        deployment_context_id: u64,
        config: &DeploymentConfig,
    ) -> Result<LiveRuntime> {
        let shard_config = &self.runtime_cfg.execution.shards;
        // Keep replacements in their existing failure domain whenever that
        // process is still tracked. For a first activation, use the stable
        // hash preference and then deterministic linear probing so ordinary
        // hash skew cannot waste otherwise available bounded shard capacity.
        let existing_slot = {
            let processes = self.shard_processes.lock().await;
            processes
                .iter()
                .find_map(|(slot, process)| process.contains(name).then_some(*slot))
        };
        let mut selected = None;
        for slot in Self::shard_candidate_slots(name, shard_config.count, existing_slot) {
            let process = self.ensure_shard_process(slot).await?;
            if process.reserve(name, shard_config.max_apps)? {
                selected = Some((slot, process));
                break;
            }
        }
        let (slot, process) = selected.ok_or_else(|| {
            anyhow!(
                "all {} worker shards are at their {}-deployment capacity while placing {name:?}",
                shard_config.count,
                shard_config.max_apps
            )
        })?;

        let runtime_generation = WORKER_SOCKET_SEQUENCE.fetch_add(1, Ordering::Relaxed);
        let runtime_id = format!(
            "r-{}-{}-{runtime_generation}",
            std::process::id(),
            process.generation
        );
        let absolute_library = std::fs::canonicalize(dylib_path).with_context(|| {
            format!("canonicalizing shard application {}", dylib_path.display())
        })?;
        let spec = WorkerDeploymentSpec {
            deployment: name.to_string(),
            runtime_id: runtime_id.clone(),
            dylib_path: absolute_library,
            module_name: module_name.map(str::to_owned),
            executor_stack_size_bytes: self.runtime_cfg.execution.executor_stack_size_bytes,
            command_queue_capacity: self.runtime_cfg.execution.command_queue_capacity,
            gc_reclaim_check_interval: self.runtime_cfg.execution.gc_reclaim_check_interval,
            gc_reclaim_growth_bytes: self.runtime_cfg.execution.gc_reclaim_growth_bytes,
            deployment_context_id,
            queue_policies: WorkerQueuePolicies::from_config(config)
                .queues
                .into_iter()
                .map(|policy| ShardQueuePolicy {
                    name: policy.name,
                    max_payload_bytes: policy.max_payload_bytes,
                    max_attempts: policy.max_attempts,
                    max_delay_ms: policy.max_delay_ms,
                })
                .collect(),
        };

        if let Err(error) = WorkerClient::load_shard_deployment(&process.socket_path, spec).await {
            process.release(name);
            if error.is_uncertain() {
                self.retire_shard_failure_domain(&process, "load_transport")
                    .await;
            }
            return Err(anyhow!(error))
                .with_context(|| format!("loading deployment {name} in worker shard {slot}"));
        }
        let client = match WorkerClient::connect_shard(name, &runtime_id, &process.socket_path)
            .await
        {
            Ok(client) => Arc::new(client),
            Err(error) => {
                process.release(name);
                if let Err(cleanup_error) =
                    WorkerClient::unload_shard_deployment(&process.socket_path, name, &runtime_id)
                        .await
                {
                    warn!(
                        deployment = name,
                        shard_slot = slot,
                        shard_generation = process.generation,
                        runtime_id,
                        ?cleanup_error,
                        "could not confirm cleanup after shard dispatch connection failed"
                    );
                    self.retire_shard_failure_domain(&process, "activation_cleanup")
                        .await;
                }
                return Err(error).with_context(|| {
                    format!("connecting deployment {name} to worker shard {slot}")
                });
            }
        };

        info!(
            deployment = name,
            shard_slot = slot,
            shard_generation = process.generation,
            shard_pid = process.pid,
            runtime_id,
            requested_isolation = config.isolation.class.requested_label(),
            effective_isolation = "sharded",
            "application generation loaded into worker shard"
        );
        Ok(LiveRuntime::Shard {
            runtime_id,
            client,
            process,
        })
    }

    /// A load whose response cannot be correlated may already have created a
    /// live native executor. The daemon must not release its logical
    /// reservation and leave that executor unreachable. Retire the complete
    /// advertised shard failure domain; the health supervisor will recreate
    /// any already-published siblings from their immutable packages.
    async fn retire_shard_failure_domain(&self, process: &Arc<ShardProcess>, reason: &'static str) {
        if process.mark_poisoned() {
            crate::metrics::record_shard_failure(process.slot, reason);
        }
        let clients = {
            let live = self.live.read().await;
            live.values()
                .filter_map(|deployment| match &deployment.runtime {
                    LiveRuntime::Shard {
                        process: resident,
                        client,
                        ..
                    } if Arc::ptr_eq(resident, process) => Some(client.clone()),
                    _ => None,
                })
                .collect::<Vec<_>>()
        };
        for client in &clients {
            client.mark_poisoned(
                WorkerPoisonCause::ShardLifecycle,
                "worker shard lifecycle outcome is uncertain",
            );
        }
        warn!(
            shard_slot = process.slot,
            shard_generation = process.generation,
            shard_pid = process.pid,
            affected_live_deployments = clients.len(),
            reason,
            "retiring worker shard after an uncertain lifecycle operation"
        );
        process.terminate().await;

        // Do not remove a newer process that raced with this retirement.
        let mut processes = self.shard_processes.lock().await;
        if processes
            .get(&process.slot)
            .is_some_and(|current| Arc::ptr_eq(current, process))
        {
            processes.remove(&process.slot);
        }
    }

    async fn ensure_shard_process(&self, slot: usize) -> Result<Arc<ShardProcess>> {
        let mut processes = self.shard_processes.lock().await;
        if let Some(process) = processes.get(&slot).cloned() {
            let running = if process.is_poisoned() {
                false
            } else {
                process
                    .child
                    .lock()
                    .await
                    .try_wait()
                    .with_context(|| format!("checking worker shard {slot}"))?
                    .is_none()
            };
            if running {
                return Ok(process);
            }
            process.terminate().await;
            processes.remove(&slot);
        }

        let process = match self.spawn_shard_process(slot).await {
            Ok(process) => {
                crate::metrics::record_shard_start(slot, "success");
                process
            }
            Err(error) => {
                crate::metrics::record_shard_start(slot, "failure");
                return Err(error);
            }
        };
        processes.insert(slot, process.clone());
        Ok(process)
    }

    async fn spawn_shard_process(&self, slot: usize) -> Result<Arc<ShardProcess>> {
        std::fs::create_dir_all(&self.runtime_cfg.paths.sockets_dir).with_context(|| {
            format!(
                "creating sockets dir {}",
                self.runtime_cfg.paths.sockets_dir.display()
            )
        })?;
        let generation = WORKER_SOCKET_SEQUENCE.fetch_add(1, Ordering::Relaxed);
        let shard_id = format!("shard-{slot}");
        let socket_path = self.runtime_cfg.paths.sockets_dir.join(format!(
            "{shard_id}-{}-{generation}.sock",
            std::process::id()
        ));
        let cgroup = WorkerCgroup::prepare_shard(
            &self.runtime_cfg.execution.cgroup,
            &shard_id,
            generation,
            &self.runtime_cfg.execution.shards,
        )
        .with_context(|| format!("preparing cgroup for worker shard {slot}"))?;
        let worker_binary = self.locate_worker_binary()?;
        let mut command = tokio::process::Command::new(&worker_binary);
        command
            .arg("--shard-id")
            .arg(slot.to_string())
            .arg("--shard-max-apps")
            .arg(self.runtime_cfg.execution.shards.max_apps.to_string())
            .arg("--socket")
            .arg(&socket_path)
            .arg("--sockets-dir")
            .arg(&self.runtime_cfg.paths.sockets_dir)
            .arg("--perry-runtime")
            .arg(&self.runtime_cfg.paths.perry_runtime_library)
            .arg("--perry-stdlib")
            .arg(&self.runtime_cfg.paths.perry_stdlib_library)
            .arg("--provider-verification")
            .arg(self.runtime_cfg.execution.provider_verification.as_str())
            .arg("--parent-pid")
            .arg(std::process::id().to_string());
        if let Some(postgres) = &self.runtime_cfg.postgres {
            command.env("COOP_QUEUE_POSTGRES_URL", &postgres.url).env(
                "COOP_QUEUE_POSTGRES_MAX_CONNECTIONS",
                postgres.max_connections.clamp(1, 4).to_string(),
            );
        }
        if let Some(cgroup) = cgroup.as_ref() {
            command.arg("--cgroup-procs").arg(cgroup.procs_path());
        }
        let mut child = command
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .kill_on_drop(true)
            .spawn()
            .with_context(|| format!("spawning worker shard with {worker_binary:?}"))?;
        let pid = child.id().unwrap_or(0);

        if let Some(stdout) = child.stdout.take() {
            let shard = shard_id.clone();
            tokio::spawn(async move {
                let mut reader = tokio::io::BufReader::new(stdout);
                let mut line = String::new();
                use tokio::io::AsyncBufReadExt;
                loop {
                    line.clear();
                    match reader.read_line(&mut line).await {
                        Ok(0) => break,
                        Ok(_) => info!(
                            target: "worker.stdout",
                            shard,
                            "{}",
                            line.trim_end()
                        ),
                        Err(error) => {
                            warn!(shard, ?error, "reading worker shard stdout");
                            break;
                        }
                    }
                }
            });
        }
        if let Some(stderr) = child.stderr.take() {
            let shard = shard_id.clone();
            tokio::spawn(async move {
                let mut reader = tokio::io::BufReader::new(stderr);
                let mut line = String::new();
                use tokio::io::AsyncBufReadExt;
                loop {
                    line.clear();
                    match reader.read_line(&mut line).await {
                        Ok(0) => break,
                        Ok(_) => warn!(
                            target: "worker.stderr",
                            shard,
                            "{}",
                            line.trim_end()
                        ),
                        Err(_) => break,
                    }
                }
            });
        }

        let deadline = std::time::Instant::now() + Duration::from_secs(5);
        loop {
            if let Some(status) = child
                .try_wait()
                .with_context(|| format!("checking worker shard {slot} startup"))?
            {
                return Err(anyhow!(
                    "worker shard {slot} exited before handshake ({status})"
                ));
            }
            match WorkerClient::connect_shard("__probe__", "__probe__", &socket_path).await {
                Ok(client) => {
                    drop(client);
                    break;
                }
                Err(error) if std::time::Instant::now() < deadline => {
                    tokio::time::sleep(Duration::from_millis(10)).await;
                    let _ = error;
                }
                Err(error) => {
                    let _ = child.kill().await;
                    let _ = child.wait().await;
                    let _ = std::fs::remove_file(&socket_path);
                    return Err(error)
                        .with_context(|| format!("waiting for worker shard {slot} handshake"));
                }
            }
        }

        info!(
            shard_slot = slot,
            shard_generation = generation,
            pid,
            socket = %socket_path.display(),
            cgroup = ?cgroup.as_ref().map(WorkerCgroup::path),
            max_apps = self.runtime_cfg.execution.shards.max_apps,
            "worker shard ready"
        );
        Ok(Arc::new(ShardProcess {
            slot,
            generation,
            socket_path,
            child: TokioMutex::new(child),
            pid,
            cgroup,
            poisoned: AtomicBool::new(false),
            reservations: StdMutex::new(ShardReservations::default()),
        }))
    }

    fn parse_crons(config: &DeploymentConfig) -> Result<Vec<ParsedCron>> {
        config
            .crons
            .iter()
            .map(|cron| {
                let normalized = if cron.schedule.split_whitespace().count() == 5 {
                    format!("0 {}", cron.schedule)
                } else {
                    cron.schedule.clone()
                };
                let schedule = Schedule::from_str(&normalized).with_context(|| {
                    format!(
                        "invalid cron expression {:?} for {}",
                        cron.schedule,
                        cron.file.display()
                    )
                })?;
                Ok(ParsedCron {
                    expression: cron.schedule.clone(),
                    schedule,
                    overlap: cron.overlap,
                    late: cron.late,
                    max_lateness_ms: cron.max_lateness_ms,
                })
            })
            .collect()
    }

    fn prepare_cron_tasks(
        deployment: &str,
        crons: Vec<ParsedCron>,
        target: DeploymentInvocationTarget,
        stop: CancellationToken,
    ) -> PreparedCronTasks {
        let mut handles = Vec::with_capacity(crons.len());
        let mut activators = Vec::with_capacity(crons.len());
        for cron in crons {
            let (activate, activated) = tokio::sync::oneshot::channel();
            activators.push(activate);
            let target = target.clone();
            let deployment = deployment.to_string();
            let stop = stop.clone();
            handles.push(tokio::spawn(async move {
                tokio::select! {
                    biased;
                    _ = stop.cancelled() => return,
                    activated = activated => if activated.is_err() { return },
                }
                info!(deployment = %deployment, schedule = %cron.expression, "cron task activated");
                let mut in_flight = tokio::task::JoinSet::new();
                loop {
                    while let Some(joined) = in_flight.try_join_next() {
                        if let Err(error) = joined {
                            crate::metrics::record_cron_completion(
                                &deployment,
                                &cron.expression,
                                "task_failure",
                                0.0,
                            );
                            error!(deployment = %deployment, schedule = %cron.expression, ?error, "cron invocation task failed");
                        }
                    }
                    let now = chrono::Utc::now();
                    let Some(next) = cron.schedule.upcoming(chrono::Utc).next() else {
                        warn!(deployment = %deployment, schedule = %cron.expression, "cron schedule exhausted");
                        break;
                    };
                    let wait = (next - now).to_std().unwrap_or_default();
                    tokio::select! {
                        biased;
                        _ = stop.cancelled() => break,
                        _ = tokio::time::sleep(wait) => {}
                    }
                    let dispatched_at = chrono::Utc::now();
                    let lateness_ms = (dispatched_at - next).num_milliseconds().max(0) as u64;
                    crate::metrics::record_cron_lateness(
                        &deployment,
                        &cron.expression,
                        lateness_ms as f64 / 1_000.0,
                    );
                    match cron_tick_decision(
                        cron.overlap,
                        cron.late,
                        cron.max_lateness_ms,
                        lateness_ms,
                        !in_flight.is_empty(),
                    ) {
                        CronTickDecision::SkipLate => {
                            crate::metrics::record_cron_schedule(
                                &deployment,
                                &cron.expression,
                                "skipped_late",
                            );
                            warn!(
                                deployment = %deployment,
                                schedule = %cron.expression,
                                lateness_ms,
                                max_lateness_ms = cron.max_lateness_ms,
                                "cron fire skipped because scheduler lateness exceeded policy"
                            );
                            continue;
                        }
                        CronTickDecision::SkipOverlap => {
                            crate::metrics::record_cron_schedule(
                                &deployment,
                                &cron.expression,
                                "skipped_overlap",
                            );
                            warn!(
                                deployment = %deployment,
                                schedule = %cron.expression,
                                in_flight = in_flight.len(),
                                "cron fire skipped because the prior fire is still active"
                            );
                            continue;
                        }
                        CronTickDecision::Dispatch => {}
                    }
                    let context = coop_host_abi::CronContext {
                        expression: cron.expression.clone(),
                        scheduled_at_ms: next.timestamp_millis().max(0) as u64,
                        dispatched_at_ms: dispatched_at.timestamp_millis().max(0) as u64,
                    };
                    crate::metrics::record_cron_schedule(
                        &deployment,
                        &cron.expression,
                        "dispatched",
                    );
                    let invocation_target = target.clone();
                    let invocation_deployment = deployment.clone();
                    let invocation_schedule = cron.expression.clone();
                    in_flight.spawn(async move {
                        let started = std::time::Instant::now();
                        let result = invocation_target.fire_cron(context).await;
                        let outcome = match &result {
                            Ok(()) => "success",
                            Err(InvocationError::DeadlineExceeded { .. }) => "timeout",
                            Err(InvocationError::Overloaded { .. }) => "overloaded",
                            Err(_) => "failure",
                        };
                        crate::metrics::record_cron_completion(
                            &invocation_deployment,
                            &invocation_schedule,
                            outcome,
                            started.elapsed().as_secs_f64(),
                        );
                        if let Err(error) = result {
                            error!(deployment = %invocation_deployment, schedule = %invocation_schedule, ?error, "cron invocation failed");
                        }
                    });
                }
                // Generation shutdown does not abandon an already dispatched
                // fire. Invocation deadlines bound this join, and the outer
                // background-task drain adds a five-second grace.
                while let Some(joined) = in_flight.join_next().await {
                    if let Err(error) = joined {
                        crate::metrics::record_cron_completion(
                            &deployment,
                            &cron.expression,
                            "task_failure",
                            0.0,
                        );
                        error!(deployment = %deployment, schedule = %cron.expression, ?error, "cron invocation task failed during drain");
                    }
                }
            }));
        }
        PreparedCronTasks {
            handles,
            activators,
        }
    }

    fn prepare_queue_tasks(
        deployment: &str,
        queues: Vec<crate::config::QueueConfig>,
        target: DeploymentInvocationTarget,
        store: Arc<QueueStore>,
        generation: String,
        stop: CancellationToken,
    ) -> PreparedQueueTasks {
        let mut handles = Vec::new();
        let mut activators = Vec::new();

        for queue in queues {
            for worker_index in 0..queue.concurrency {
                let (activate, activated) = tokio::sync::oneshot::channel();
                activators.push(activate);
                let deployment = deployment.to_string();
                let queue = queue.clone();
                let target = target.clone();
                let store = store.clone();
                let generation = generation.clone();
                let stop = stop.clone();
                handles.push(tokio::spawn(async move {
                    tokio::select! {
                        biased;
                        _ = stop.cancelled() => return,
                        activated = activated => if activated.is_err() { return },
                    }
                    info!(
                        deployment = %deployment,
                        queue = %queue.name,
                        worker_index,
                        generation = %generation,
                        "durable queue consumer activated"
                    );

                    let poll_interval = Duration::from_millis(queue.poll_interval_ms);
                    let visibility = Duration::from_millis(queue.visibility_timeout_ms);
                    let mut consecutive_store_errors = 0_u32;
                    loop {
                        if stop.is_cancelled() {
                            return;
                        }
                        let permit = match target.try_admit_queue() {
                            Ok(permit) => permit,
                            Err(InvocationError::Overloaded { .. }) => {
                                crate::metrics::record_queue_deferred(
                                    &deployment,
                                    &queue.name,
                                    "admission",
                                );
                                if wait_or_stop(&stop, poll_interval).await {
                                    return;
                                }
                                continue;
                            }
                            Err(error) => {
                                warn!(deployment = %deployment, queue = %queue.name, ?error, "queue admission failed");
                                if wait_or_stop(&stop, poll_interval).await {
                                    return;
                                }
                                continue;
                            }
                        };

                        let claim = tokio::select! {
                            biased;
                            _ = stop.cancelled() => {
                                drop(permit);
                                return;
                            }
                            claim = store.claim(
                                &deployment,
                                &queue.name,
                                &generation,
                                visibility,
                            ) => claim,
                        };
                        let claim = match claim {
                            Ok(Some(claim)) => {
                                consecutive_store_errors = 0;
                                claim
                            }
                            Ok(None) => {
                                consecutive_store_errors = 0;
                                drop(permit);
                                if wait_or_stop(&stop, poll_interval).await {
                                    return;
                                }
                                continue;
                            }
                            Err(error) => {
                                drop(permit);
                                crate::metrics::record_queue_store_error("claim");
                                consecutive_store_errors =
                                    consecutive_store_errors.saturating_add(1);
                                let retry_after = queue_store_error_backoff(
                                    poll_interval,
                                    consecutive_store_errors,
                                );
                                if consecutive_store_errors == 1
                                    || consecutive_store_errors.is_power_of_two()
                                {
                                    warn!(
                                        deployment = %deployment,
                                        queue = %queue.name,
                                        consecutive_errors = consecutive_store_errors,
                                        retry_after_ms = retry_after.as_millis(),
                                        ?error,
                                        "durable queue claim failed"
                                    );
                                }
                                if wait_or_stop(&stop, retry_after).await {
                                    return;
                                }
                                continue;
                            }
                        };

                        if stop.is_cancelled() {
                            drop(permit);
                            if let Err(error) = store
                                .release_without_attempt(&claim, Duration::ZERO)
                                .await
                            {
                                crate::metrics::record_queue_store_error("release");
                                warn!(deployment = %deployment, queue = %queue.name, ?error, "failed to release queue claim during generation stop");
                            }
                            return;
                        }

                        crate::metrics::record_queue_claim(
                            &deployment,
                            &queue.name,
                            claim.recovered_expired_lease,
                        );
                        let message = coop_host_abi::QueueDispatchMessage {
                            queue_name: queue.name.clone(),
                            message_id: claim.id.clone(),
                            attempt: claim.attempt,
                            max_retries: claim.max_attempts.saturating_sub(1),
                            payload: claim.payload.clone(),
                        };
                        let started = std::time::Instant::now();
                        let result = target.deliver_admitted_queue(message, permit).await;
                        let outcome = Self::settle_queue_delivery(
                            &store,
                            &deployment,
                            &queue,
                            &claim,
                            result,
                        )
                        .await;
                        crate::metrics::record_queue_delivery(
                            &deployment,
                            &queue.name,
                            outcome,
                            started.elapsed().as_secs_f64(),
                        );
                    }
                }));
            }

            // One low-frequency inventory/pruning task per queue, independent
            // of delivery concurrency.
            let (activate, activated) = tokio::sync::oneshot::channel();
            activators.push(activate);
            let deployment = deployment.to_string();
            let queue = queue.clone();
            let store = store.clone();
            let stop = stop.clone();
            handles.push(tokio::spawn(async move {
                tokio::select! {
                    biased;
                    _ = stop.cancelled() => return,
                    activated = activated => if activated.is_err() { return },
                }
                let mut interval = tokio::time::interval(Duration::from_secs(5));
                interval.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Delay);
                let mut last_prune = tokio::time::Instant::now() - Duration::from_secs(3600);
                loop {
                    tokio::select! {
                        biased;
                        _ = stop.cancelled() => return,
                        _ = interval.tick() => {}
                    }
                    match store.stats(&deployment, &queue.name).await {
                        Ok(stats) => crate::metrics::set_queue_stats(
                            &deployment,
                            &queue.name,
                            stats.total_depth,
                            stats.visible_depth,
                            stats.active_leases,
                            stats.oldest_visible_age_seconds,
                            stats.dead_letters,
                        ),
                        Err(error) => {
                            crate::metrics::record_queue_store_error("stats");
                            warn!(deployment = %deployment, queue = %queue.name, ?error, "reading durable queue metrics failed");
                        }
                    }
                    if queue.dlq_retention_days > 0
                        && last_prune.elapsed() >= Duration::from_secs(3600)
                    {
                        let retention = Duration::from_secs(
                            u64::from(queue.dlq_retention_days) * 24 * 60 * 60,
                        );
                        match store
                            .prune_dead_letters(&deployment, &queue.name, retention)
                            .await
                        {
                            Ok(removed) => crate::metrics::record_queue_dlq_pruned(
                                &deployment,
                                &queue.name,
                                removed,
                            ),
                            Err(error) => {
                                crate::metrics::record_queue_store_error("prune_dlq");
                                warn!(deployment = %deployment, queue = %queue.name, ?error, "pruning durable queue DLQ failed");
                            }
                        }
                        last_prune = tokio::time::Instant::now();
                    }
                }
            }));
        }

        PreparedQueueTasks {
            handles,
            activators,
        }
    }

    async fn settle_queue_delivery(
        store: &QueueStore,
        deployment: &str,
        queue: &crate::config::QueueConfig,
        claim: &ClaimedMessage,
        result: Result<coop_host_abi::QueueDisposition, InvocationError>,
    ) -> &'static str {
        use coop_host_abi::QueueDisposition;
        match result {
            Ok(QueueDisposition::Ack) => match store.ack(claim).await {
                Ok(true) => "ack",
                Ok(false) => "lease_lost",
                Err(error) => {
                    crate::metrics::record_queue_store_error("ack");
                    warn!(deployment, queue = %queue.name, message_id = %claim.id, ?error, "durable queue ack failed");
                    "store_error"
                }
            },
            Ok(QueueDisposition::Nack) => {
                Self::retry_queue_delivery(store, deployment, queue, claim, "handler returned nack")
                    .await
            }
            Ok(QueueDisposition::Dlq) => {
                match store
                    .dead_letter(claim, "handler returned dead-letter")
                    .await
                {
                    Ok(RetryOutcome::DeadLettered) => "dlq",
                    Ok(RetryOutcome::LeaseLost) => "lease_lost",
                    Ok(RetryOutcome::Scheduled { .. }) => unreachable!(),
                    Err(error) => {
                        crate::metrics::record_queue_store_error("dead_letter");
                        warn!(deployment, queue = %queue.name, message_id = %claim.id, ?error, "moving queue message to DLQ failed");
                        "store_error"
                    }
                }
            }
            Err(InvocationError::RequestTooLarge { .. }) => {
                match store
                    .dead_letter(claim, "queue payload exceeds deployment limit")
                    .await
                {
                    Ok(RetryOutcome::DeadLettered) => "payload_dlq",
                    Ok(RetryOutcome::LeaseLost) => "lease_lost",
                    Ok(RetryOutcome::Scheduled { .. }) => unreachable!(),
                    Err(error) => {
                        crate::metrics::record_queue_store_error("dead_letter");
                        warn!(deployment, queue = %queue.name, message_id = %claim.id, ?error, "moving oversized queue message to DLQ failed");
                        "store_error"
                    }
                }
            }
            Err(error @ InvocationError::DeadlineExceeded { .. }) => {
                match store.mark_lease_error(claim, &error.to_string()).await {
                    Ok(true) => "timeout_leased",
                    Ok(false) => "lease_lost",
                    Err(store_error) => {
                        crate::metrics::record_queue_store_error("mark_timeout");
                        warn!(deployment, queue = %queue.name, message_id = %claim.id, ?store_error, "recording queue timeout failed");
                        "store_error"
                    }
                }
            }
            Err(error) => {
                Self::retry_queue_delivery(store, deployment, queue, claim, &error.to_string())
                    .await
            }
        }
    }

    async fn retry_queue_delivery(
        store: &QueueStore,
        deployment: &str,
        queue: &crate::config::QueueConfig,
        claim: &ClaimedMessage,
        error: &str,
    ) -> &'static str {
        match store
            .retry(
                claim,
                error,
                Duration::from_millis(queue.retry_base_delay_ms),
                Duration::from_millis(queue.retry_max_delay_ms),
            )
            .await
        {
            Ok(RetryOutcome::Scheduled { .. }) => {
                crate::metrics::record_queue_retry(deployment, &queue.name, "scheduled");
                "retry"
            }
            Ok(RetryOutcome::DeadLettered) => {
                crate::metrics::record_queue_retry(deployment, &queue.name, "exhausted_dlq");
                "exhausted_dlq"
            }
            Ok(RetryOutcome::LeaseLost) => "lease_lost",
            Err(error) => {
                crate::metrics::record_queue_store_error("retry");
                warn!(deployment, queue = %queue.name, message_id = %claim.id, ?error, "durable queue retry transition failed");
                "store_error"
            }
        }
    }

    /// Locate the coop-worker binary. Tries in order: runtime.toml
    /// explicit path, `$PATH`, the daemon's own directory.
    fn locate_worker_binary(&self) -> Result<PathBuf> {
        if let Some(p) = &self.runtime_cfg.paths.coop_worker_binary {
            return Ok(p.clone());
        }

        // Try the same directory as the daemon binary itself.
        if let Ok(exe) = std::env::current_exe() {
            if let Some(dir) = exe.parent() {
                let candidate = dir.join("coop-worker");
                if candidate.exists() {
                    return Ok(candidate);
                }
            }
        }

        // Fall back to PATH.
        Ok(PathBuf::from("coop-worker"))
    }

    async fn run_compiler(
        &self,
        deployment: &str,
        command: &mut tokio::process::Command,
    ) -> Result<CompilerRunOutput> {
        command
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .kill_on_drop(true);
        #[cfg(unix)]
        command.process_group(0);

        let mut child = command.spawn().context("spawning Perry compiler")?;
        let pid = child
            .id()
            .ok_or_else(|| anyhow!("Perry compiler started without a process ID"))?;
        test_pause_at_process_crash_point("compiler_started", deployment, Some(pid)).await;
        let stdout = child
            .stdout
            .take()
            .ok_or_else(|| anyhow!("Perry compiler stdout pipe was not created"))?;
        let stderr = child
            .stderr
            .take()
            .ok_or_else(|| anyhow!("Perry compiler stderr pipe was not created"))?;
        let output_limit = self.runtime_cfg.execution.compile_output_bytes;
        let stdout_task = tokio::spawn(Self::drain_compiler_output(stdout, output_limit));
        let stderr_task = tokio::spawn(Self::drain_compiler_output(stderr, output_limit));

        let timeout = Duration::from_secs(self.runtime_cfg.execution.compile_timeout_seconds);
        let max_rss_kib = self
            .runtime_cfg
            .execution
            .compile_max_rss_mb
            .saturating_mul(1024);
        let deadline = tokio::time::sleep(timeout);
        tokio::pin!(deadline);
        let mut interval = tokio::time::interval(Duration::from_millis(100));
        interval.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Skip);
        let mut peak_rss_kib = 0u64;
        let mut violation = None;

        let status = loop {
            tokio::select! {
                status = child.wait() => break status.context("waiting for Perry compiler")?,
                _ = &mut deadline => {
                    violation = Some(CompilerViolation::WallTimeout);
                    Self::terminate_compiler(&mut child, pid);
                    break child.wait().await.context("reaping timed-out Perry compiler")?;
                }
                _ = interval.tick(), if max_rss_kib > 0 => {
                    match Self::process_group_rss_kib(pid).await {
                        Ok(rss_kib) => {
                            peak_rss_kib = peak_rss_kib.max(rss_kib);
                            if rss_kib > max_rss_kib {
                                violation = Some(CompilerViolation::RssLimit {
                                    sampled_kib: rss_kib,
                                    limit_kib: max_rss_kib,
                                });
                                Self::terminate_compiler(&mut child, pid);
                                break child.wait().await.context("reaping RSS-limited Perry compiler")?;
                            }
                        }
                        Err(error) => {
                            violation = Some(CompilerViolation::RssMonitor(format!("{error:#}")));
                            Self::terminate_compiler(&mut child, pid);
                            break child.wait().await.context("reaping unmonitored Perry compiler")?;
                        }
                    }
                }
            }
        };

        let stdout = stdout_task
            .await
            .context("joining Perry compiler stdout drain")??;
        let stderr = stderr_task
            .await
            .context("joining Perry compiler stderr drain")??;
        Ok(CompilerRunOutput {
            status,
            stdout,
            stderr,
            peak_rss_kib,
            violation,
        })
    }

    fn guarded_compiler_command(perry_binary: &Path) -> Result<tokio::process::Command> {
        #[cfg(unix)]
        {
            let daemon_binary = std::env::current_exe()
                .context("locating Coop executable for compiler parent guard")?;
            let mut command = tokio::process::Command::new(daemon_binary);
            command
                .arg("compiler-guard")
                .arg("--parent-pid")
                .arg(std::process::id().to_string())
                .arg("--")
                .arg(perry_binary);
            Ok(command)
        }
        #[cfg(not(unix))]
        {
            Ok(tokio::process::Command::new(perry_binary))
        }
    }

    fn record_perry_cache_stats(deployment: &str, stdout: &[u8], stderr: &[u8]) {
        let value = String::from_utf8_lossy(stdout)
            .lines()
            .rev()
            .find_map(|line| serde_json::from_str::<serde_json::Value>(line).ok());
        if let Some(value) = &value {
            info!(
                deployment,
                report = %value,
                "Perry compiler cache report"
            );
        }
        let mut recorded_codegen = false;
        if let Some(codegen) = value.as_ref().and_then(|value| value.get("codegen_cache")) {
            for (field, outcome) in [
                ("hits", "hit"),
                ("misses", "miss"),
                ("stores", "store"),
                ("store_errors", "store_error"),
            ] {
                if let Some(entries) = codegen.get(field).and_then(serde_json::Value::as_u64) {
                    crate::metrics::record_compile_cache_entries(
                        deployment,
                        "perry_codegen",
                        outcome,
                        entries,
                    );
                    recorded_codegen = true;
                }
            }
        }
        if !recorded_codegen {
            let diagnostic = String::from_utf8_lossy(stderr);
            if let Some((hits, misses)) = diagnostic.lines().find_map(|line| {
                let report = line.split_once("codegen cache:")?.1.trim();
                let (hits, rest) = report.split_once('/')?;
                let (total, _) = rest.split_once(' ')?;
                let hits = hits.trim().parse::<u64>().ok()?;
                let total = total.trim().parse::<u64>().ok()?;
                (hits <= total).then_some((hits, total - hits))
            }) {
                crate::metrics::record_compile_cache_entries(
                    deployment,
                    "perry_codegen",
                    "hit",
                    hits,
                );
                crate::metrics::record_compile_cache_entries(
                    deployment,
                    "perry_codegen",
                    "miss",
                    misses,
                );
                info!(deployment, hits, misses, "Perry codegen cache result");
                recorded_codegen = true;
            }
        }
        if !recorded_codegen {
            crate::metrics::record_compile_cache_entries(
                deployment,
                "perry_codegen",
                "unavailable",
                1,
            );
        }
        if let Some(link) = value.as_ref().and_then(|value| value.get("link_cache")) {
            let outcome = if link
                .get("skipped")
                .and_then(serde_json::Value::as_bool)
                .unwrap_or(false)
            {
                "hit"
            } else if link
                .get("linked")
                .and_then(serde_json::Value::as_bool)
                .unwrap_or(false)
            {
                "miss"
            } else {
                "unavailable"
            };
            crate::metrics::record_compile_cache_entries(deployment, "perry_link", outcome, 1);
        }
    }

    async fn drain_compiler_output<R>(mut reader: R, limit: usize) -> std::io::Result<Vec<u8>>
    where
        R: tokio::io::AsyncRead + Unpin,
    {
        let mut retained = Vec::with_capacity(limit.min(64 * 1024));
        let mut chunk = [0u8; 16 * 1024];
        loop {
            let read = reader.read(&mut chunk).await?;
            if read == 0 {
                break;
            }
            let remaining = limit.saturating_sub(retained.len());
            retained.extend_from_slice(&chunk[..read.min(remaining)]);
        }
        Ok(retained)
    }

    async fn process_group_rss_kib(process_group: u32) -> Result<u64> {
        let output = tokio::process::Command::new("ps")
            .args(["-axo", "pgid=,rss="])
            .output()
            .await
            .context("running ps for compiler RSS enforcement")?;
        if !output.status.success() {
            return Err(anyhow!(
                "ps failed while enforcing compiler RSS (exit {})",
                output.status
            ));
        }
        let listing =
            String::from_utf8(output.stdout).context("ps emitted non-UTF-8 compiler RSS output")?;
        Ok(listing
            .lines()
            .filter_map(|line| {
                let mut fields = line.split_whitespace();
                let pgid = fields.next()?.parse::<u32>().ok()?;
                let rss = fields.next()?.parse::<u64>().ok()?;
                (pgid == process_group).then_some(rss)
            })
            .sum())
    }

    fn terminate_compiler(child: &mut Child, process_group: u32) {
        #[cfg(unix)]
        // SAFETY: `process_group` is the positive PID returned by the child we
        // started with `process_group(0)`. Negating it targets only that new
        // compiler group, never the daemon's process group.
        unsafe {
            libc::kill(-(process_group as i32), libc::SIGKILL);
        }
        let _ = child.start_kill();
    }

    /// Compile a deployment's handler TS files into a shared library via
    /// `perry compile --output-type dylib`. Exact build-input identity, not
    /// timestamps or a mutable legacy path, decides whether compilation can be
    /// skipped.
    async fn compile_deployment(
        &self,
        name: &str,
        deployment_dir: &Path,
        module_name: Option<&str>,
        deployment_config: &DeploymentConfig,
    ) -> Result<PathBuf> {
        let cache_started = std::time::Instant::now();
        let identity_phase = CompilePhaseMetric::new(name, "identity");
        let ext = if cfg!(target_os = "macos") {
            "dylib"
        } else {
            "so"
        };
        let reserved_entry = deployment_dir.join("coop_entry.ts");
        if reserved_entry.exists() {
            let existing = std::fs::read_to_string(&reserved_entry).with_context(|| {
                format!(
                    "reading reserved generated entry {}",
                    reserved_entry.display()
                )
            })?;
            if existing.starts_with(GENERATED_ENTRY_MARKER) {
                std::fs::remove_file(&reserved_entry).with_context(|| {
                    format!(
                        "removing incomplete generated entry {}",
                        reserved_entry.display()
                    )
                })?;
            } else {
                return Err(anyhow!(
                    "{} is reserved for Coop's generated multi-entry root; rename the user-owned file",
                    reserved_entry.display()
                ));
            }
        }
        // Collect every local module/config input that Perry may read. Static
        // roots and installed dependencies have separate exact identities.
        let mut source_files: Vec<PathBuf> = Vec::new();
        Self::collect_source_files(deployment_dir, &mut source_files)?;
        source_files.retain(|path| {
            !deployment_config
                .static_blocks
                .iter()
                .any(|block| path.starts_with(deployment_dir.join(&block.directory)))
        });
        source_files.sort();

        let has_source_module = source_files.iter().any(|path| {
            path.extension()
                .and_then(|extension| extension.to_str())
                .is_some_and(|extension| matches!(extension, "ts" | "tsx" | "js" | "mjs" | "cjs"))
        });
        if !has_source_module {
            // Source-less deployments may select an already published,
            // content-addressed package. The removed mutable
            // `compiled/<name>.<ext>` fallback is intentionally not consulted.
            let current_dylib = Self::latest_compiled_artifact(
                &self.runtime_cfg.paths.compiled_dir,
                name,
                ext,
                None,
            );
            if let Some(dylib_path) = current_dylib {
                identity_phase.success();
                info!(
                    deployment = name,
                    dylib = %dylib_path.display(),
                    "no TS files found, using existing compiled dylib"
                );
                return Ok(dylib_path);
            }
            return Err(anyhow!(
                "deployment {name} has no compiler inputs and no published immutable package"
            ));
        }

        let compiler_identity = self.compiler_build_identity().await?;
        let dependency_sha256 = Self::deployment_dependency_sha256(
            deployment_dir,
            self.runtime_cfg.execution.compile_dependency_max_files,
            self.runtime_cfg.execution.compile_dependency_max_bytes,
        )?;
        let mutable_source_sha256 = Self::deployment_source_sha256_with_dependency(
            deployment_dir,
            deployment_config,
            &source_files,
            &dependency_sha256,
        )?;
        let source_sha256 =
            Self::build_input_sha256(&mutable_source_sha256, &compiler_identity.sha256);
        let mut compiler_snapshot_config = deployment_config.clone();
        compiler_snapshot_config.static_blocks.clear();
        compiler_snapshot_config.activation = crate::config::ActivationConfig::default();
        let compiler_mutable_source_sha256 = Self::deployment_source_sha256_with_dependency(
            deployment_dir,
            &compiler_snapshot_config,
            &source_files,
            &dependency_sha256,
        )?;
        let compiler_source_sha256 =
            Self::build_input_sha256(&compiler_mutable_source_sha256, &compiler_identity.sha256);
        let current_dylib = Self::latest_compiled_artifact(
            &self.runtime_cfg.paths.compiled_dir,
            name,
            ext,
            Some(&source_sha256),
        );
        let target = Self::host_target();
        let manifest = current_dylib
            .as_deref()
            .map(AppLibraryManifest::load)
            .transpose()
            .with_context(|| format!("reading manifest for deployment {name}"))?
            .flatten();
        let manifest_matches = manifest.as_ref().is_some_and(|manifest| {
            let provider = perry_provider_identity();
            manifest.abi_version == APP_LIBRARY_ABI_VERSION
                && manifest.deployment == name
                && manifest.perry_version == coop_app_host::PERRY_RUNTIME_VERSION
                && manifest.perry_commit == coop_app_host::PERRY_RUNTIME_COMMIT
                && manifest.compiler_sha256 == provider.compiler_sha256
                && manifest.target == target
                && manifest.init_symbol == "perry_module_init"
                && manifest.boundary_verified
                && manifest.boundary_verification_version
                    == coop_host_abi::APP_LIBRARY_BOUNDARY_VERSION
                && manifest.library_sha256.is_some()
                && manifest.source_sha256.as_deref() == Some(source_sha256.as_str())
                && manifest.dependency_sha256.as_deref() == Some(dependency_sha256.as_str())
                && manifest.compiler_invocation_sha256.as_deref()
                    == Some(compiler_identity.sha256.as_str())
                && manifest.library_size.is_some_and(|expected| {
                    current_dylib
                        .as_deref()
                        .ok_or_else(|| std::io::Error::from(std::io::ErrorKind::NotFound))
                        .and_then(std::fs::metadata)
                        .map(|metadata| metadata.len() == expected)
                        .unwrap_or(false)
                })
        }) && current_dylib.as_deref().is_some_and(|library| {
            self.artifact_store
                .package_id_for_library(name, library)
                .is_some_and(|package| self.artifact_store.verify_package(name, &package).is_ok())
        });

        // Source/config bytes and every provider/compiler identity are exact;
        // no filesystem timestamp participates in cache correctness.
        let needs_compile = !manifest_matches;
        identity_phase.success();

        if !needs_compile {
            crate::metrics::record_compile_cache_entries(name, "package", "hit", 1);
            let dylib_path = current_dylib.expect("up-to-date artifact must exist");
            crate::metrics::record_compile(
                name,
                "success",
                "hit",
                cache_started.elapsed().as_secs_f64(),
                0,
            );
            info!(
                deployment = name,
                dylib = %dylib_path.display(),
                "dylib is up-to-date, skipping compile"
            );
            return Ok(dylib_path);
        }
        crate::metrics::record_compile_cache_entries(name, "package", "miss", 1);

        let reusable_dylib = Self::latest_compiled_code_artifact(
            &self.runtime_cfg.paths.compiled_dir,
            name,
            ext,
            &compiler_source_sha256,
            &dependency_sha256,
            &compiler_identity.sha256,
        )
        .filter(|library| {
            self.artifact_store
                .package_id_for_library(name, library)
                .is_some_and(|package| self.artifact_store.verify_package(name, &package).is_ok())
        });
        crate::metrics::record_compile_cache_entries(
            name,
            "compiled_code",
            if reusable_dylib.is_some() {
                "hit"
            } else {
                "miss"
            },
            1,
        );

        let perry_binary = &compiler_identity.perry_binary;
        let compiler_version = compiler_identity.perry_version.clone();

        // Perry accepts one root module. Always compile a generated root so
        // every configured entry is present in one application library and
        // the public Coop ABI can use stable aliases rather than Perry's
        // path-derived internal wrapper names.
        let snapshot_phase = CompilePhaseMetric::new(name, "snapshot");
        let source_args: Vec<PathBuf> = source_files
            .iter()
            .map(|path| Self::process_absolute(path))
            .collect::<Result<_>>()?;
        let staging_dir = self.artifact_store.ensure_staging_root()?.join(format!(
            "{name}-{}-{}",
            std::process::id(),
            STAGING_SEQUENCE.fetch_add(1, Ordering::Relaxed)
        ));
        std::fs::create_dir_all(&staging_dir)
            .with_context(|| format!("creating staged package {}", staging_dir.display()))?;
        let mut staged_package = StagedPackage::new(staging_dir.clone());
        let source_snapshot = staging_dir.join(".coop-source");
        Self::copy_source_snapshot(
            deployment_dir,
            &source_snapshot,
            &source_files,
            self.runtime_cfg.execution.compile_dependency_max_files,
            self.runtime_cfg.execution.compile_dependency_max_bytes,
        )?;
        let mut snapshot_files = Vec::new();
        Self::collect_source_files(&source_snapshot, &mut snapshot_files)?;
        snapshot_files.sort();
        let snapshot_dependency_sha256 = Self::deployment_dependency_sha256(
            &source_snapshot,
            self.runtime_cfg.execution.compile_dependency_max_files,
            self.runtime_cfg.execution.compile_dependency_max_bytes,
        )?;
        if snapshot_dependency_sha256 != dependency_sha256 {
            return Err(anyhow!(
                "deployment {name} dependencies changed while its compiler snapshot was being created"
            ));
        }
        let snapshot_mutable_sha256 = Self::deployment_source_sha256_with_dependency(
            &source_snapshot,
            &compiler_snapshot_config,
            &snapshot_files,
            &snapshot_dependency_sha256,
        )?;
        let snapshot_sha256 =
            Self::build_input_sha256(&snapshot_mutable_sha256, &compiler_identity.sha256);
        if snapshot_sha256 != compiler_source_sha256 {
            return Err(anyhow!(
                "deployment {name} changed while its compiler snapshot was being created"
            ));
        }
        let dylib_path = staging_dir.join(format!("app.{ext}"));
        let output_path = Self::process_absolute(&dylib_path)?;
        let compile_dir = Self::process_absolute(&source_snapshot)?;
        let module_name = module_name.ok_or_else(|| {
            anyhow!("deployment {name} has TypeScript sources but no configured handler")
        })?;
        let generated_entry = compile_dir.join("coop_entry.ts");
        let handle_export = APP_HTTP_ENTRY_SYMBOL.to_string();
        let has_http_handler = source_files.iter().any(|path| {
            let path_module = path.file_name().and_then(|file| file.to_str()).map(|file| {
                file.replace(|c: char| !c.is_alphanumeric() && c != '_', "_")
                    .trim_start_matches('_')
                    .to_string()
            });
            path_module.as_deref() == Some(module_name)
                && std::fs::read_to_string(path)
                    .map(|source| Self::has_buffer_http_handler(&source))
                    .unwrap_or(false)
        });
        if !has_http_handler {
            return Err(anyhow!(
                "deployment {name} must export handle(request: Buffer): Buffer from its configured handler"
            ));
        }
        let cron_entries = deployment_config
            .crons
            .iter()
            .enumerate()
            .map(|(index, cron)| {
                Self::require_buffer_handler(deployment_dir, &cron.file, "cron")?;
                Ok(CronLibraryEntry {
                    expression: cron.schedule.clone(),
                    symbol: format!("coop_app_cron_{index}_v2"),
                    handler_abi: HandlerAbi::Wrapped,
                })
            })
            .collect::<Result<Vec<_>>>()?;
        let queue_entries = deployment_config
            .queues
            .iter()
            .enumerate()
            .map(|(index, queue)| {
                Self::require_buffer_handler(deployment_dir, &queue.file, "queue")?;
                Ok(QueueLibraryEntry {
                    queue_name: queue.name.clone(),
                    symbol: format!("coop_app_queue_{index}_v2"),
                    handler_abi: HandlerAbi::Wrapped,
                })
            })
            .collect::<Result<Vec<_>>>()?;
        let mut app_exports = vec!["perry_module_init".to_string(), handle_export.clone()];
        app_exports.extend(cron_entries.iter().map(|entry| entry.symbol.clone()));
        app_exports.extend(queue_entries.iter().map(|entry| entry.symbol.clone()));
        app_exports.sort();
        app_exports.dedup();
        let exports_path = output_path.with_extension("coop-exports");
        Self::write_app_exports_file(&exports_path, &app_exports)?;
        let aliases_path = output_path.with_extension("coop-aliases");
        let mut aliases = format!("{APP_HTTP_ENTRY_SYMBOL}\t__{GENERATED_HTTP_FUNCTION}\n");
        for (index, entry) in cron_entries.iter().enumerate() {
            aliases.push_str(&format!("{}\t__coopCron{index}\n", entry.symbol));
        }
        for (index, entry) in queue_entries.iter().enumerate() {
            aliases.push_str(&format!("{}\t__coopQueue{index}\n", entry.symbol));
        }
        std::fs::write(&aliases_path, aliases)
            .with_context(|| format!("writing app entry alias specification {:?}", aliases_path))?;

        let mut source = String::from(GENERATED_ENTRY_MARKER);
        let http_input = Self::process_absolute(
            &source_snapshot.join(
                &deployment_config
                    .handlers
                    .first()
                    .expect("module name requires an HTTP handler")
                    .file,
            ),
        )?;
        source.push_str(&format!(
            "import {{ handle as coopHttpHandler }} from {};\n",
            serde_json::to_string(&http_input.to_string_lossy())?
        ));
        source.push_str(&format!(
            "export function {GENERATED_HTTP_FUNCTION}(frame: Buffer): any {{ return coopHttpHandler(frame); }}\n"
        ));
        for (index, cron) in deployment_config.crons.iter().enumerate() {
            let entry_path = Self::process_absolute(&source_snapshot.join(&cron.file))?;
            source.push_str(&format!(
                "import {{ handle as coopCronHandler{index} }} from {};\n",
                serde_json::to_string(&entry_path.to_string_lossy())?
            ));
            source.push_str(&format!(
                "export function coopCron{index}(frame: Buffer): any {{ return coopCronHandler{index}(frame); }}\n"
            ));
        }
        for (index, queue) in deployment_config.queues.iter().enumerate() {
            let entry_path = Self::process_absolute(&source_snapshot.join(&queue.file))?;
            source.push_str(&format!(
                "import {{ handle as coopQueueHandler{index} }} from {};\n",
                serde_json::to_string(&entry_path.to_string_lossy())?
            ));
            source.push_str(&format!(
                "export function coopQueue{index}(frame: Buffer): any {{ return coopQueueHandler{index}(frame); }}\n"
            ));
        }
        std::fs::write(&generated_entry, source).with_context(|| {
            format!(
                "writing generated Perry entry {}",
                generated_entry.display()
            )
        })?;
        let compile_input = &generated_entry;
        let compile_argument = compile_input.strip_prefix(&compile_dir).with_context(|| {
            format!(
                "compiler root {} is outside source snapshot {}",
                compile_input.display(),
                compile_dir.display()
            )
        })?;
        info!(
            deployment = name,
            perry = %perry_binary.display(),
            compiler_identity = %compiler_identity.sha256,
            dependency_identity = %dependency_sha256,
            cache_dir = %compiler_identity.cache_dir.display(),
            files = ?source_args,
            root = %compile_input.display(),
            output = %dylib_path.display(),
            "compiling deployment"
        );

        let mut compile = Self::guarded_compiler_command(&perry_binary)?;
        compile
            .arg("compile")
            // Host-declared code generation can execute arbitrary programs
            // and mutate inputs. Production packages require generated bytes
            // to be committed before Coop snapshots them.
            .arg("--no-codegen")
            // Dylib output never links Perry's static archives. Disable its
            // auto-specialization pass too, otherwise Perry may rebuild a
            // per-app runtime/stdlib pair that the dylib link then discards.
            .arg("--no-auto-optimize")
            .arg("--march")
            .arg(&self.runtime_cfg.execution.compile_march)
            .arg("--output-type")
            .arg("dylib")
            .arg("--format")
            .arg("json")
            .arg("--cache-dir")
            .arg(&compiler_identity.cache_dir)
            .arg("-o")
            .arg(&output_path)
            // Keep the entry module identity independent of staging/package
            // roots. An absolute argv path causes Perry to bake the complete
            // temporary path into exported wrapper symbols whenever a project
            // package.json is present.
            .arg(compile_argument)
            .current_dir(&compile_dir)
            // Perry inherits only this audited environment. In particular,
            // ambient PERRY_* feature switches cannot silently change emitted
            // code without changing Coop configuration and build identity.
            .env_clear()
            .env("PATH", &compiler_identity.compiler_path)
            .envs(compiler_identity.propagated_environment.iter().cloned())
            .env("COOP_REAL_CC", &compiler_identity.real_cc)
            // Perry computes object-cache counts for dylibs but currently
            // exposes them only through this bounded diagnostic line.
            .env("PERRY_DEV_VERBOSE", "1")
            .env("COOP_APP_EXPORTS_FILE", &exports_path)
            .env("COOP_APP_ALIASES_FILE", &aliases_path)
            .env(
                "COOP_PERRY_RUNTIME_LIBRARY",
                Self::process_absolute(&self.runtime_cfg.paths.perry_runtime_library)?,
            )
            .env(
                "COOP_PERRY_STDLIB_LIBRARY",
                Self::process_absolute(&self.runtime_cfg.paths.perry_stdlib_library)?,
            );
        snapshot_phase.success();
        let compiler_phase = CompilePhaseMetric::new(name, "compiler");
        let compiler_started = std::time::Instant::now();
        let (compiler_duration, peak_rss_bytes, compile_cache) = if let Some(reusable) =
            reusable_dylib
        {
            // Immutable packages share an inode when the artifact store is on
            // one filesystem. This avoids another app-image allocation and
            // lets the platform loader recognize byte-identical code. Copy is
            // a portability fallback for filesystems without hard links.
            // Loading a second handle for the same hard-linked native image
            // while its first executor is alive can alias loader/module state.
            // A hard link is safe when the live image differs, or when the
            // activation path is guaranteed to retain the healthy initialized
            // runtime instead of loading the new package path.
            let hard_link_safe = {
                let live = self.live.read().await;
                match live.get(name) {
                    None => true,
                    Some(current) => {
                        let same_live_image =
                            Self::same_compiled_application_image(&current.dylib_path, &reusable)?;
                        !same_live_image
                            || (!RuntimeDispatchTarget::from_runtime(&current.runtime)
                                .requires_replacement()
                                && current.config.queues == deployment_config.queues
                                && current.config.limits.max_queue_payload_bytes
                                    == deployment_config.limits.max_queue_payload_bytes)
                    }
                }
            };
            let hard_linked = hard_link_safe && std::fs::hard_link(&reusable, &dylib_path).is_ok();
            if !hard_linked {
                std::fs::copy(&reusable, &dylib_path).with_context(|| {
                    format!(
                        "reusing verified application image {} as {}",
                        reusable.display(),
                        dylib_path.display()
                    )
                })?;
            }
            std::fs::remove_dir_all(&source_snapshot).with_context(|| {
                format!(
                    "removing compiler source snapshot {}",
                    source_snapshot.display()
                )
            })?;
            let _ = std::fs::remove_file(&exports_path);
            let _ = std::fs::remove_file(&aliases_path);
            let duration = compiler_started.elapsed().as_secs_f64();
            compiler_phase.success();
            info!(
                deployment = name,
                source = %reusable.display(),
                hard_linked,
                elapsed_ms = duration * 1_000.0,
                "reused verified compiled application image"
            );
            (duration, 0, "code_hit")
        } else {
            let output_result = self.run_compiler(name, &mut compile).await;
            std::fs::remove_dir_all(&source_snapshot).with_context(|| {
                format!(
                    "removing compiler source snapshot {}",
                    source_snapshot.display()
                )
            })?;
            let _ = std::fs::remove_file(&exports_path);
            let _ = std::fs::remove_file(&aliases_path);
            let output = match output_result {
                Ok(output) => output,
                Err(error) => {
                    crate::metrics::record_compile(
                        name,
                        "spawn_failure",
                        "miss",
                        compiler_started.elapsed().as_secs_f64(),
                        0,
                    );
                    return Err(error).with_context(|| {
                        format!(
                            "running perry compile for deployment {} (binary: {:?})",
                            name, perry_binary
                        )
                    });
                }
            };
            let compiler_duration = compiler_started.elapsed().as_secs_f64();
            let peak_rss_bytes = output.peak_rss_kib.saturating_mul(1024);
            if let Some(violation) = &output.violation {
                crate::metrics::record_compile(
                    name,
                    violation.metric_outcome(),
                    "miss",
                    compiler_duration,
                    peak_rss_bytes,
                );
                let detail = match violation {
                    CompilerViolation::WallTimeout => format!(
                        "wall time exceeded {} seconds",
                        self.runtime_cfg.execution.compile_timeout_seconds
                    ),
                    CompilerViolation::RssLimit {
                        sampled_kib,
                        limit_kib,
                    } => format!("process-group RSS {sampled_kib} KiB exceeded {limit_kib} KiB"),
                    CompilerViolation::RssMonitor(error) => {
                        format!("RSS enforcement became unavailable: {error}")
                    }
                };
                return Err(anyhow!(
                    "perry compile terminated for deployment {name}: {detail}\nstderr: {}\nstdout: {}",
                    String::from_utf8_lossy(&output.stderr).trim(),
                    String::from_utf8_lossy(&output.stdout).trim(),
                ));
            }
            if !output.status.success() {
                crate::metrics::record_compile(
                    name,
                    "compiler_failure",
                    "miss",
                    compiler_duration,
                    peak_rss_bytes,
                );
                let stderr = String::from_utf8_lossy(&output.stderr);
                let stdout = String::from_utf8_lossy(&output.stdout);
                return Err(anyhow!(
                    "perry compile failed for deployment {} (exit {})\nstderr: {}\nstdout: {}",
                    name,
                    output.status,
                    stderr.trim(),
                    stdout.trim(),
                ));
            }
            compiler_phase.success();
            info!(
                deployment = name,
                elapsed_ms = compiler_duration * 1_000.0,
                peak_rss_bytes,
                "Perry compiler process completed"
            );
            Self::record_perry_cache_stats(name, &output.stdout, &output.stderr);
            (compiler_duration, peak_rss_bytes, "miss")
        };
        let validation_phase = CompilePhaseMetric::new(name, "validation");
        let post_compile_dependency_sha256 = Self::deployment_dependency_sha256(
            deployment_dir,
            self.runtime_cfg.execution.compile_dependency_max_files,
            self.runtime_cfg.execution.compile_dependency_max_bytes,
        )
        .context("rechecking dependency identity after compilation")?;
        let post_compile_mutable_sha256 = Self::deployment_source_sha256_with_dependency(
            deployment_dir,
            deployment_config,
            &source_files,
            &post_compile_dependency_sha256,
        )
        .context("rechecking deployment snapshot identity after compilation")?;
        let post_compile_source_sha256 =
            Self::build_input_sha256(&post_compile_mutable_sha256, &compiler_identity.sha256);
        if post_compile_source_sha256 != source_sha256 {
            crate::metrics::record_compile(
                name,
                "source_changed",
                "miss",
                compiler_duration,
                peak_rss_bytes,
            );
            return Err(anyhow!(
                "deployment {name} changed while Perry was compiling; discarded staged output"
            ));
        }
        crate::metrics::record_compile(
            name,
            "success",
            compile_cache,
            compiler_duration,
            peak_rss_bytes,
        );
        if !dylib_path.exists() {
            return Err(anyhow!(
                "perry compile succeeded but dylib {:?} was not created",
                dylib_path
            ));
        }

        let handle_symbol = handle_export;
        let handler_abi = HandlerAbi::Wrapped;
        let compiled_exports = Self::list_exports(&dylib_path)?;
        for symbol in app_exports
            .iter()
            .filter(|symbol| *symbol != "perry_module_init")
        {
            if !compiled_exports.contains(symbol) {
                return Err(anyhow!(
                    "compiled library is missing configured entry export {symbol}"
                ));
            }
        }
        coop_app_host::plugin_host::validate_library_boundary(&dylib_path)
            .with_context(|| format!("validating app-library boundary for {name}"))?;
        let library_size = std::fs::metadata(&dylib_path)
            .with_context(|| format!("reading compiled library metadata for {name}"))?
            .len();
        let library_sha256 = coop_app_host::plugin_host::library_sha256(&dylib_path)?;
        validation_phase.success();
        test_pause_at_process_crash_point("staging_validated", name, None).await;
        let package_phase = CompilePhaseMetric::new(name, "package");
        let (packaged_config, static_manifest_bytes) = self.artifact_store.snapshot_static_assets(
            &staging_dir,
            deployment_dir,
            deployment_config,
        )?;
        let publication_dependency_sha256 = Self::deployment_dependency_sha256(
            deployment_dir,
            self.runtime_cfg.execution.compile_dependency_max_files,
            self.runtime_cfg.execution.compile_dependency_max_bytes,
        )
        .context("rechecking dependency identity before publication")?;
        let publication_mutable_sha256 = Self::deployment_source_sha256_with_dependency(
            deployment_dir,
            deployment_config,
            &source_files,
            &publication_dependency_sha256,
        )
        .context("rechecking deployment identity before publication")?;
        let publication_source_sha256 =
            Self::build_input_sha256(&publication_mutable_sha256, &compiler_identity.sha256);
        if publication_source_sha256 != source_sha256 {
            return Err(anyhow!(
                "deployment {name} changed while its immutable package was being assembled"
            ));
        }
        let manifest = AppLibraryManifest {
            abi_version: APP_LIBRARY_ABI_VERSION,
            deployment: name.to_string(),
            perry_version: compiler_version,
            perry_commit: coop_app_host::PERRY_RUNTIME_COMMIT.to_string(),
            compiler_sha256: perry_provider_identity().compiler_sha256.clone(),
            target,
            init_symbol: "perry_module_init".to_string(),
            handle_symbol,
            handler_abi,
            cron_entries,
            queue_entries,
            boundary_verified: true,
            boundary_verification_version: coop_host_abi::APP_LIBRARY_BOUNDARY_VERSION,
            library_sha256: Some(library_sha256.clone()),
            library_size: Some(library_size),
            source_sha256: Some(source_sha256),
            compile_source_sha256: Some(compiler_source_sha256),
            dependency_sha256: Some(dependency_sha256),
            compiler_invocation_sha256: Some(compiler_identity.sha256.clone()),
        };
        let staged_manifest_path = manifest
            .write(&dylib_path)
            .with_context(|| format!("writing app-library manifest for {name}"))?;
        let (_staged_config_path, packaged_config_bytes) =
            ArtifactStore::write_packaged_config(&staging_dir, &packaged_config)?;

        // The library and manifest become visible together by renaming their
        // containing directory. A digest collision with different or invalid
        // bytes is an integrity error; an identical existing package is a
        // cache hit and is reused without mutation.
        Self::sync_file(&dylib_path)?;
        Self::sync_file(&staged_manifest_path)?;
        Self::sync_directory(&staging_dir)?;
        let artifact_parent = self.artifact_store.ensure_namespace(name)?;
        let manifest_bytes = std::fs::read(&staged_manifest_path)
            .context("reading staged app manifest for package identity")?;
        let package_sha256 = ArtifactStore::package_digest_with_static(
            &manifest_bytes,
            &packaged_config_bytes,
            &static_manifest_bytes,
        );
        let artifact_dir = artifact_parent.join(&package_sha256);
        let published_dylib = artifact_dir.join(format!("app.{ext}"));
        package_phase.success();
        let publication_phase = CompilePhaseMetric::new(name, "publication");
        if artifact_dir.exists() {
            self.artifact_store
                .verify_package(name, &package_sha256)
                .with_context(|| {
                    format!(
                        "validating existing immutable package {}",
                        artifact_dir.display()
                    )
                })?;
            let existing_digest = coop_app_host::plugin_host::library_sha256(&published_dylib)
                .with_context(|| {
                    format!(
                        "validating existing immutable package {}",
                        artifact_dir.display()
                    )
                })?;
            let existing_manifest = AppLibraryManifest::load(&published_dylib)
                .with_context(|| {
                    format!(
                        "reading existing immutable package {}",
                        artifact_dir.display()
                    )
                })?
                .ok_or_else(|| {
                    anyhow!(
                        "immutable package has no manifest: {}",
                        artifact_dir.display()
                    )
                })?;
            if existing_digest != library_sha256 || existing_manifest != manifest {
                return Err(anyhow!(
                    "content-addressed package collision or corruption at {}",
                    artifact_dir.display()
                ));
            }
        } else {
            let published =
                self.artifact_store
                    .publish_staging_package(name, &package_sha256, &staging_dir)?;
            debug_assert_eq!(published, artifact_dir);
            staged_package.mark_published();
        }
        publication_phase.success();

        info!(
            deployment = name,
            dylib = %published_dylib.display(),
            library_sha256 = %library_sha256,
            package_sha256 = %package_sha256,
            "compilation succeeded and immutable package was published"
        );

        Ok(published_dylib)
    }

    fn latest_compiled_artifact(
        compiled_dir: &Path,
        name: &str,
        ext: &str,
        expected_source_sha256: Option<&str>,
    ) -> Option<PathBuf> {
        let namespace = compiled_dir.join(name);
        let entries = std::fs::read_dir(namespace).ok()?;
        entries
            .flatten()
            .filter_map(|entry| {
                let library = entry.path().join(format!("app.{ext}"));
                let modified = std::fs::metadata(&library).ok()?.modified().ok()?;
                let manifest = AppLibraryManifest::load(&library).ok().flatten()?;
                if expected_source_sha256.is_some()
                    && manifest.source_sha256.as_deref() != expected_source_sha256
                {
                    return None;
                }
                Some((modified, library))
            })
            .max_by_key(|(modified, _)| *modified)
            .map(|(_, library)| library)
    }

    fn latest_compiled_code_artifact(
        compiled_dir: &Path,
        name: &str,
        ext: &str,
        compile_source_sha256: &str,
        dependency_sha256: &str,
        compiler_invocation_sha256: &str,
    ) -> Option<PathBuf> {
        let namespace = compiled_dir.join(name);
        std::fs::read_dir(namespace)
            .ok()?
            .flatten()
            .filter_map(|entry| {
                let library = entry.path().join(format!("app.{ext}"));
                let modified = std::fs::metadata(&library).ok()?.modified().ok()?;
                let manifest = AppLibraryManifest::load(&library).ok().flatten()?;
                (manifest.compile_source_sha256.as_deref() == Some(compile_source_sha256)
                    && manifest.dependency_sha256.as_deref() == Some(dependency_sha256)
                    && manifest.compiler_invocation_sha256.as_deref()
                        == Some(compiler_invocation_sha256))
                .then_some((modified, library))
            })
            .max_by_key(|(modified, _)| *modified)
            .map(|(_, library)| library)
    }

    fn copy_source_snapshot(
        deployment_dir: &Path,
        snapshot_dir: &Path,
        source_files: &[PathBuf],
        max_dependency_files: usize,
        max_dependency_bytes: u64,
    ) -> Result<()> {
        std::fs::create_dir_all(snapshot_dir).with_context(|| {
            format!(
                "creating compiler source snapshot {}",
                snapshot_dir.display()
            )
        })?;
        for source in source_files {
            let relative = source.strip_prefix(deployment_dir).with_context(|| {
                format!(
                    "compiler input {} is outside deployment {}",
                    source.display(),
                    deployment_dir.display()
                )
            })?;
            let metadata = std::fs::symlink_metadata(source)
                .with_context(|| format!("reading compiler input metadata {}", source.display()))?;
            if metadata.file_type().is_symlink() || !metadata.is_file() {
                return Err(anyhow!(
                    "compiler input is not a plain file: {}",
                    source.display()
                ));
            }
            let destination = snapshot_dir.join(relative);
            if let Some(parent) = destination.parent() {
                std::fs::create_dir_all(parent).with_context(|| {
                    format!("creating compiler snapshot directory {}", parent.display())
                })?;
            }
            std::fs::copy(source, &destination).with_context(|| {
                format!(
                    "copying compiler input {} to {}",
                    source.display(),
                    destination.display()
                )
            })?;
        }

        // Dereference the complete installed dependency closure into the
        // private snapshot. This is deliberately conservative until Perry
        // exposes its resolved module graph: hashing/copying an unused package
        // costs deployment time, but can never return a stale build.
        let dependencies = deployment_dir.join("node_modules");
        match std::fs::symlink_metadata(&dependencies) {
            Ok(metadata) if metadata.is_dir() || metadata.file_type().is_symlink() => {
                let mut stats = DependencyTreeStats::default();
                let mut active_directories = HashSet::new();
                Self::copy_dependency_entry(
                    &dependencies,
                    &snapshot_dir.join("node_modules"),
                    Path::new(""),
                    &mut stats,
                    max_dependency_files,
                    max_dependency_bytes,
                    &mut active_directories,
                )?;
            }
            Ok(_) => {
                return Err(anyhow!(
                    "deployment node_modules is not a directory: {}",
                    dependencies.display()
                ))
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
            Err(error) => {
                return Err(error).with_context(|| {
                    format!("reading dependency directory {}", dependencies.display())
                })
            }
        }
        Ok(())
    }

    #[allow(clippy::too_many_arguments)]
    fn copy_dependency_entry(
        source: &Path,
        destination: &Path,
        logical_path: &Path,
        stats: &mut DependencyTreeStats,
        max_files: usize,
        max_bytes: u64,
        active_directories: &mut HashSet<PathBuf>,
    ) -> Result<()> {
        let link_metadata = std::fs::symlink_metadata(source)
            .with_context(|| format!("reading dependency input {}", source.display()))?;
        let resolved = if link_metadata.file_type().is_symlink() {
            source
                .canonicalize()
                .with_context(|| format!("resolving dependency symlink {}", source.display()))?
        } else {
            source.to_path_buf()
        };
        let metadata = std::fs::metadata(&resolved)
            .with_context(|| format!("reading dependency target {}", resolved.display()))?;

        if metadata.is_dir() {
            let canonical = resolved.canonicalize().with_context(|| {
                format!("canonicalizing dependency directory {}", resolved.display())
            })?;
            if !active_directories.insert(canonical.clone()) {
                return Err(anyhow!(
                    "dependency symlink cycle reaches {}",
                    canonical.display()
                ));
            }
            std::fs::create_dir_all(destination).with_context(|| {
                format!("creating dependency snapshot {}", destination.display())
            })?;
            let mut entries = std::fs::read_dir(&resolved)
                .with_context(|| format!("reading dependency directory {}", resolved.display()))?
                .collect::<std::io::Result<Vec<_>>>()?;
            entries.sort_by_key(std::fs::DirEntry::file_name);
            for entry in entries {
                let child_logical = logical_path.join(entry.file_name());
                if Self::skip_dependency_path(&child_logical) {
                    continue;
                }
                Self::copy_dependency_entry(
                    &entry.path(),
                    &destination.join(entry.file_name()),
                    &child_logical,
                    stats,
                    max_files,
                    max_bytes,
                    active_directories,
                )?;
            }
            active_directories.remove(&canonical);
            return Ok(());
        }
        if !metadata.is_file() {
            return Err(anyhow!(
                "dependency input is not a file or directory: {}",
                resolved.display()
            ));
        }

        stats.files = stats
            .files
            .checked_add(1)
            .ok_or_else(|| anyhow!("dependency file count overflow"))?;
        stats.bytes = stats
            .bytes
            .checked_add(metadata.len())
            .ok_or_else(|| anyhow!("dependency byte count overflow"))?;
        if stats.files > max_files {
            return Err(anyhow!(
                "dependency snapshot exceeds file limit {max_files} at {}",
                source.display()
            ));
        }
        if stats.bytes > max_bytes {
            return Err(anyhow!(
                "dependency snapshot exceeds byte limit {max_bytes} at {}",
                source.display()
            ));
        }
        if let Some(parent) = destination.parent() {
            std::fs::create_dir_all(parent).with_context(|| {
                format!(
                    "creating dependency snapshot directory {}",
                    parent.display()
                )
            })?;
        }
        let copied = std::fs::copy(&resolved, destination).with_context(|| {
            format!(
                "copying dependency input {} to {}",
                resolved.display(),
                destination.display()
            )
        })?;
        if copied != metadata.len() {
            return Err(anyhow!(
                "dependency input changed while copying {}: expected {} bytes, copied {copied}",
                resolved.display(),
                metadata.len()
            ));
        }
        Ok(())
    }

    fn deployment_dependency_sha256(
        deployment_dir: &Path,
        max_files: usize,
        max_bytes: u64,
    ) -> Result<String> {
        let mut digest = Sha256::new();
        digest.update(b"coop-dependency-tree-v1\0");
        let dependencies = deployment_dir.join("node_modules");
        match std::fs::symlink_metadata(&dependencies) {
            Ok(metadata) if metadata.is_dir() || metadata.file_type().is_symlink() => {
                let mut stats = DependencyTreeStats::default();
                let mut active_directories = HashSet::new();
                Self::hash_dependency_entry(
                    &dependencies,
                    Path::new(""),
                    &mut digest,
                    &mut stats,
                    max_files,
                    max_bytes,
                    &mut active_directories,
                )?;
                Self::digest_field(&mut digest, "files", &stats.files.to_be_bytes());
                Self::digest_field(&mut digest, "bytes", &stats.bytes.to_be_bytes());
            }
            Ok(_) => {
                return Err(anyhow!(
                    "deployment node_modules is not a directory: {}",
                    dependencies.display()
                ));
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                Self::digest_field(&mut digest, "state", b"absent");
            }
            Err(error) => {
                return Err(error).with_context(|| {
                    format!("reading dependency directory {}", dependencies.display())
                });
            }
        }
        Ok(format!("{:x}", digest.finalize()))
    }

    #[allow(clippy::too_many_arguments)]
    fn hash_dependency_entry(
        source: &Path,
        logical_path: &Path,
        digest: &mut Sha256,
        stats: &mut DependencyTreeStats,
        max_files: usize,
        max_bytes: u64,
        active_directories: &mut HashSet<PathBuf>,
    ) -> Result<()> {
        let logical = Self::dependency_logical_path(logical_path)?;
        let link_metadata = std::fs::symlink_metadata(source)
            .with_context(|| format!("reading dependency input {}", source.display()))?;
        let resolved = if link_metadata.file_type().is_symlink() {
            source
                .canonicalize()
                .with_context(|| format!("resolving dependency symlink {}", source.display()))?
        } else {
            source.to_path_buf()
        };
        let metadata = std::fs::metadata(&resolved)
            .with_context(|| format!("reading dependency target {}", resolved.display()))?;

        if metadata.is_dir() {
            Self::digest_field(digest, "directory", logical.as_bytes());
            let canonical = resolved.canonicalize().with_context(|| {
                format!("canonicalizing dependency directory {}", resolved.display())
            })?;
            if !active_directories.insert(canonical.clone()) {
                return Err(anyhow!(
                    "dependency symlink cycle reaches {}",
                    canonical.display()
                ));
            }
            let mut entries = std::fs::read_dir(&resolved)
                .with_context(|| format!("reading dependency directory {}", resolved.display()))?
                .collect::<std::io::Result<Vec<_>>>()?;
            entries.sort_by_key(std::fs::DirEntry::file_name);
            for entry in entries {
                let child_logical = logical_path.join(entry.file_name());
                if Self::skip_dependency_path(&child_logical) {
                    continue;
                }
                Self::hash_dependency_entry(
                    &entry.path(),
                    &child_logical,
                    digest,
                    stats,
                    max_files,
                    max_bytes,
                    active_directories,
                )?;
            }
            active_directories.remove(&canonical);
            return Ok(());
        }
        if !metadata.is_file() {
            return Err(anyhow!(
                "dependency input is not a file or directory: {}",
                resolved.display()
            ));
        }

        stats.files = stats
            .files
            .checked_add(1)
            .ok_or_else(|| anyhow!("dependency file count overflow"))?;
        stats.bytes = stats
            .bytes
            .checked_add(metadata.len())
            .ok_or_else(|| anyhow!("dependency byte count overflow"))?;
        if stats.files > max_files {
            return Err(anyhow!(
                "dependency graph exceeds file limit {max_files} at {}",
                source.display()
            ));
        }
        if stats.bytes > max_bytes {
            return Err(anyhow!(
                "dependency graph exceeds byte limit {max_bytes} at {}",
                source.display()
            ));
        }
        Self::digest_field(digest, "file", logical.as_bytes());
        Self::digest_field(
            digest,
            "mode",
            &Self::dependency_mode(&metadata).to_be_bytes(),
        );
        Self::digest_field(digest, "size", &metadata.len().to_be_bytes());
        use std::io::Read;
        let mut file = std::io::BufReader::new(
            std::fs::File::open(&resolved)
                .with_context(|| format!("opening dependency input {}", resolved.display()))?,
        );
        let mut buffer = [0_u8; 64 * 1024];
        loop {
            let count = file
                .read(&mut buffer)
                .with_context(|| format!("hashing dependency input {}", resolved.display()))?;
            if count == 0 {
                break;
            }
            digest.update(&buffer[..count]);
        }
        Ok(())
    }

    fn dependency_logical_path(path: &Path) -> Result<String> {
        path.components()
            .map(|component| {
                component
                    .as_os_str()
                    .to_str()
                    .ok_or_else(|| anyhow!("dependency path is not UTF-8: {}", path.display()))
            })
            .collect::<Result<Vec<_>>>()
            .map(|parts| parts.join("/"))
    }

    fn skip_dependency_path(path: &Path) -> bool {
        let mut components = path.components();
        components
            .next()
            .is_some_and(|part| part.as_os_str() == ".cache")
            && components
                .next()
                .is_some_and(|part| part.as_os_str() == "perry")
    }

    #[cfg(unix)]
    fn dependency_mode(metadata: &std::fs::Metadata) -> u32 {
        use std::os::unix::fs::PermissionsExt;
        metadata.permissions().mode() & 0o777
    }

    #[cfg(not(unix))]
    fn dependency_mode(metadata: &std::fs::Metadata) -> u32 {
        u32::from(metadata.permissions().readonly())
    }

    fn deployment_source_sha256(
        deployment_dir: &Path,
        config: &DeploymentConfig,
        sorted_ts_files: &[PathBuf],
    ) -> Result<String> {
        let dependency_sha256 =
            Self::deployment_dependency_sha256(deployment_dir, usize::MAX, u64::MAX)?;
        Self::deployment_source_sha256_with_dependency(
            deployment_dir,
            config,
            sorted_ts_files,
            &dependency_sha256,
        )
    }

    fn deployment_source_sha256_with_dependency(
        deployment_dir: &Path,
        config: &DeploymentConfig,
        sorted_ts_files: &[PathBuf],
        dependency_sha256: &str,
    ) -> Result<String> {
        let mut digest = Sha256::new();
        digest.update(b"coop-deployment-source-v2\0");
        Self::digest_field(&mut digest, "dependencies", dependency_sha256.as_bytes());
        let config_bytes = serde_json::to_vec(config).context("serializing deployment config")?;
        digest.update((config_bytes.len() as u64).to_be_bytes());
        digest.update(config_bytes);
        let mut paths: Vec<&PathBuf> = sorted_ts_files.iter().collect();
        paths.sort();
        for path in paths {
            let relative = path.strip_prefix(deployment_dir).with_context(|| {
                format!(
                    "source {} is outside deployment {}",
                    path.display(),
                    deployment_dir.display()
                )
            })?;
            let relative = relative.to_string_lossy();
            let bytes = std::fs::read(path)
                .with_context(|| format!("reading deployment source {}", path.display()))?;
            digest.update((relative.len() as u64).to_be_bytes());
            digest.update(relative.as_bytes());
            digest.update((bytes.len() as u64).to_be_bytes());
            digest.update(bytes);
        }
        for (index, block) in config.static_blocks.iter().enumerate() {
            digest.update(b"static\0");
            digest.update((index as u64).to_be_bytes());
            let root = deployment_dir.join(&block.directory);
            Self::hash_static_source_tree(&root, &root, &mut digest)?;
        }
        Ok(format!("{:x}", digest.finalize()))
    }

    fn hash_static_source_tree(root: &Path, directory: &Path, digest: &mut Sha256) -> Result<()> {
        let metadata = std::fs::symlink_metadata(directory)
            .with_context(|| format!("reading static source {}", directory.display()))?;
        if metadata.file_type().is_symlink() || !metadata.is_dir() {
            return Err(anyhow!(
                "static source is not a plain directory: {}",
                directory.display()
            ));
        }
        let mut entries = std::fs::read_dir(directory)
            .with_context(|| format!("reading static source {}", directory.display()))?
            .collect::<std::io::Result<Vec<_>>>()?;
        entries.sort_by_key(std::fs::DirEntry::file_name);
        for entry in entries {
            let path = entry.path();
            let relative = path.strip_prefix(root)?;
            let relative = relative
                .to_str()
                .ok_or_else(|| anyhow!("static source path is not UTF-8: {}", path.display()))?;
            let file_type = entry.file_type()?;
            if file_type.is_symlink() {
                return Err(anyhow!(
                    "static source may not contain symlinks: {}",
                    path.display()
                ));
            }
            if file_type.is_dir() {
                digest.update(b"directory\0");
                digest.update((relative.len() as u64).to_be_bytes());
                digest.update(relative.as_bytes());
                Self::hash_static_source_tree(root, &path, digest)?;
            } else if file_type.is_file() {
                let bytes = std::fs::read(&path)
                    .with_context(|| format!("reading static source {}", path.display()))?;
                digest.update(b"file\0");
                digest.update((relative.len() as u64).to_be_bytes());
                digest.update(relative.as_bytes());
                digest.update((bytes.len() as u64).to_be_bytes());
                digest.update(bytes);
            } else {
                return Err(anyhow!(
                    "static source contains non-file entry: {}",
                    path.display()
                ));
            }
        }
        Ok(())
    }

    fn sync_file(path: &Path) -> Result<()> {
        std::fs::File::open(path)
            .with_context(|| format!("opening {} for durability sync", path.display()))?
            .sync_all()
            .with_context(|| format!("syncing {}", path.display()))
    }

    fn sync_directory(path: &Path) -> Result<()> {
        std::fs::File::open(path)
            .with_context(|| format!("opening directory {} for durability sync", path.display()))?
            .sync_all()
            .with_context(|| format!("syncing directory {}", path.display()))
    }

    fn host_target() -> String {
        format!("{}-{}", std::env::consts::ARCH, std::env::consts::OS)
    }

    fn has_buffer_http_handler(source: &str) -> bool {
        let compact: String = source
            .chars()
            .filter(|character| !character.is_whitespace())
            .collect();
        ["exportfunctionhandle(", "exportasyncfunctionhandle("]
            .into_iter()
            .filter_map(|prefix| compact.find(prefix).map(|offset| &compact[offset..]))
            .filter_map(|tail| tail.split_once('{').map(|(signature, _)| signature))
            .any(|signature| {
                signature.contains(":Buffer)")
                    && (signature.ends_with(":Buffer") || signature.ends_with(":Promise<Buffer>"))
            })
    }

    fn require_buffer_handler(
        deployment_dir: &Path,
        relative_path: &Path,
        entry_kind: &str,
    ) -> Result<()> {
        let path = deployment_dir.join(relative_path);
        let source = std::fs::read_to_string(&path)
            .with_context(|| format!("reading configured {entry_kind} entry {}", path.display()))?;
        if !Self::has_buffer_http_handler(&source) {
            return Err(anyhow!(
                "configured {entry_kind} entry {} must export handle(request: Buffer): Buffer",
                relative_path.display()
            ));
        }
        Ok(())
    }

    /// Resolve a config/source path against the daemon's startup directory.
    /// Perry itself runs with the deployment as cwd for package resolution, so
    /// every executable/input/output argument passed to it must be absolute.
    fn process_absolute(path: &Path) -> Result<PathBuf> {
        if path.is_absolute() {
            Ok(path.to_path_buf())
        } else {
            Ok(std::env::current_dir()
                .context("resolving daemon startup directory")?
                .join(path))
        }
    }

    fn resolve_executable(path: &Path) -> Result<PathBuf> {
        if path.is_absolute() || path.components().count() > 1 {
            return Self::process_absolute(path);
        }

        let search_path = std::env::var_os("PATH")
            .ok_or_else(|| anyhow!("PATH is not set while locating {:?}", path))?;
        for directory in std::env::split_paths(&search_path) {
            let candidate = directory.join(path);
            if candidate.is_file() {
                return Ok(candidate);
            }
        }
        Err(anyhow!("could not locate {:?} on PATH", path))
    }

    async fn compiler_build_identity(&self) -> Result<&CompilerBuildIdentity> {
        self.compiler_identity
            .get_or_try_init(|| async {
                let perry_binary = Self::resolve_executable(&self.runtime_cfg.paths.perry_binary)?
                    .canonicalize()
                    .context("canonicalizing Perry compiler path")?;
                let perry_version = Self::perry_compiler_version(&perry_binary).await?;
                if perry_version != coop_app_host::PERRY_RUNTIME_VERSION {
                    return Err(anyhow!(
                        "Perry compiler/runtime mismatch: {:?} is {}, but Coop embeds {}",
                        perry_binary,
                        perry_version,
                        coop_app_host::PERRY_RUNTIME_VERSION
                    ));
                }
                self.verify_compiler_identity(&perry_binary).await?;

                let wrapper_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
                    .join("../../scripts/compiler-wrappers")
                    .canonicalize()
                    .context("locating Coop compiler wrappers")?;
                let wrapper_sha256 =
                    coop_app_host::plugin_host::library_sha256(&wrapper_dir.join("cc"))
                        .context("hashing Coop compiler wrapper")?;
                let real_cc = Self::resolve_executable(Path::new("cc"))?
                    .canonicalize()
                    .context("canonicalizing the native C compiler")?;
                let real_cc_sha256 = coop_app_host::plugin_host::library_sha256(&real_cc)
                    .context("hashing the native C compiler")?;
                let original_path = std::env::var_os("PATH").unwrap_or_default();
                let compiler_path = std::env::join_paths(
                    std::iter::once(wrapper_dir.clone())
                        .chain(std::env::split_paths(&original_path)),
                )
                .context("constructing Perry compiler PATH")?;
                let propagated_environment = COMPILER_ENV_ALLOWLIST
                    .iter()
                    .filter_map(|name| {
                        std::env::var_os(name).map(|value| (OsString::from(name), value))
                    })
                    .collect::<Vec<_>>();

                let provider = perry_provider_identity();
                let runtime_path =
                    Self::process_absolute(&self.runtime_cfg.paths.perry_runtime_library)?
                        .canonicalize()
                        .context("canonicalizing Perry runtime provider")?;
                let stdlib_path =
                    Self::process_absolute(&self.runtime_cfg.paths.perry_stdlib_library)?
                        .canonicalize()
                        .context("canonicalizing Perry stdlib provider")?;
                let semantic_argv = [
                    "compile",
                    "--no-codegen",
                    "--no-auto-optimize",
                    "--march",
                    self.runtime_cfg.execution.compile_march.as_str(),
                    "--output-type",
                    "dylib",
                    "--format",
                    "json",
                    "--cache-dir",
                    "$CACHE",
                    "-o",
                    "$STAGING/app",
                    "$SNAPSHOT/coop_entry.ts",
                ];
                let mut digest = Sha256::new();
                Self::digest_field(
                    &mut digest,
                    "contract",
                    COMPILER_CONTRACT_VERSION.as_bytes(),
                );
                Self::digest_field(
                    &mut digest,
                    "perry_path",
                    perry_binary.to_string_lossy().as_bytes(),
                );
                Self::digest_field(&mut digest, "perry_version", perry_version.as_bytes());
                Self::digest_field(
                    &mut digest,
                    "perry_commit",
                    provider.perry_commit.as_bytes(),
                );
                Self::digest_field(
                    &mut digest,
                    "compiler_sha256",
                    provider.compiler_sha256.as_bytes(),
                );
                Self::digest_field(
                    &mut digest,
                    "runtime_sha256",
                    provider.runtime_sha256.as_bytes(),
                );
                Self::digest_field(
                    &mut digest,
                    "stdlib_sha256",
                    provider.stdlib_sha256.as_bytes(),
                );
                Self::digest_field(
                    &mut digest,
                    "runtime_path",
                    runtime_path.to_string_lossy().as_bytes(),
                );
                Self::digest_field(
                    &mut digest,
                    "stdlib_path",
                    stdlib_path.to_string_lossy().as_bytes(),
                );
                Self::digest_field(&mut digest, "wrapper_sha256", wrapper_sha256.as_bytes());
                Self::digest_field(
                    &mut digest,
                    "real_cc_path",
                    real_cc.to_string_lossy().as_bytes(),
                );
                Self::digest_field(&mut digest, "real_cc_sha256", real_cc_sha256.as_bytes());
                Self::digest_field(&mut digest, "target", Self::host_target().as_bytes());
                for argument in semantic_argv {
                    Self::digest_field(&mut digest, "argv", argument.as_bytes());
                }
                Self::digest_field(
                    &mut digest,
                    "env:PATH",
                    compiler_path.to_string_lossy().as_bytes(),
                );
                Self::digest_field(&mut digest, "env:PERRY_DEV_VERBOSE", b"1");
                for (name, value) in &propagated_environment {
                    Self::digest_field(
                        &mut digest,
                        &format!("env:{}", name.to_string_lossy()),
                        value.to_string_lossy().as_bytes(),
                    );
                }
                let sha256 = format!("{:x}", digest.finalize());
                let cache_dir = Self::process_absolute(&self.runtime_cfg.paths.compiled_dir)?
                    .join(".perry-cache")
                    .join(&sha256);

                Ok::<CompilerBuildIdentity, anyhow::Error>(CompilerBuildIdentity {
                    perry_binary,
                    perry_version,
                    real_cc,
                    compiler_path,
                    propagated_environment,
                    cache_dir,
                    sha256,
                })
            })
            .await
    }

    fn digest_field(digest: &mut Sha256, name: &str, value: &[u8]) {
        digest.update((name.len() as u64).to_be_bytes());
        digest.update(name.as_bytes());
        digest.update((value.len() as u64).to_be_bytes());
        digest.update(value);
    }

    fn build_input_sha256(source_sha256: &str, compiler_sha256: &str) -> String {
        let mut digest = Sha256::new();
        digest.update(b"coop-build-input-v1\0");
        Self::digest_field(&mut digest, "source", source_sha256.as_bytes());
        Self::digest_field(&mut digest, "compiler", compiler_sha256.as_bytes());
        format!("{:x}", digest.finalize())
    }

    async fn verify_compiler_identity(&self, perry_binary: &Path) -> Result<()> {
        self.compiler_verified
            .get_or_try_init(|| async {
                let compiler = perry_binary.to_path_buf();
                let actual = tokio::task::spawn_blocking(move || -> Result<String> {
                    use std::io::Read;

                    let file = std::fs::File::open(&compiler)
                        .with_context(|| format!("opening Perry compiler {:?}", compiler))?;
                    let mut file = std::io::BufReader::with_capacity(8 * 1024 * 1024, file);
                    let mut digest = Sha256::new();
                    let mut buffer = vec![0_u8; 8 * 1024 * 1024];
                    loop {
                        let count = file
                            .read(&mut buffer)
                            .with_context(|| format!("hashing Perry compiler {:?}", compiler))?;
                        if count == 0 {
                            break;
                        }
                        digest.update(&buffer[..count]);
                    }
                    Ok(format!("{:x}", digest.finalize()))
                })
                .await
                .context("joining Perry compiler identity check")??;
                let expected = &perry_provider_identity().compiler_sha256;
                if &actual != expected {
                    return Err(anyhow!(
                        "Perry compiler/provider mismatch for {:?}: compiler sha256={}, provider expects {}",
                        perry_binary,
                        actual,
                        expected
                    ));
                }
                Ok::<(), anyhow::Error>(())
            })
            .await?;
        Ok(())
    }

    async fn perry_compiler_version(perry_binary: &Path) -> Result<String> {
        let output = tokio::process::Command::new(perry_binary)
            .arg("--version")
            .output()
            .await
            .with_context(|| format!("querying Perry version from {:?}", perry_binary))?;
        if !output.status.success() {
            return Err(anyhow!(
                "{:?} --version failed: {}",
                perry_binary,
                String::from_utf8_lossy(&output.stderr).trim()
            ));
        }
        let stdout = String::from_utf8_lossy(&output.stdout);
        stdout
            .split_whitespace()
            .find(|part| part.chars().next().is_some_and(|c| c.is_ascii_digit()))
            .map(str::to_string)
            .ok_or_else(|| anyhow!("could not parse Perry version from {:?}", stdout.trim()))
    }

    fn list_exports(dylib_path: &Path) -> Result<Vec<String>> {
        let mut command = std::process::Command::new("nm");
        #[cfg(target_os = "macos")]
        command.args(["-gU"]);
        #[cfg(not(target_os = "macos"))]
        command.args(["-D", "--defined-only"]);
        let output = command
            .arg(dylib_path)
            .output()
            .with_context(|| format!("listing exports from {:?}", dylib_path))?;
        if !output.status.success() {
            return Err(anyhow!(
                "nm failed for {:?}: {}",
                dylib_path,
                String::from_utf8_lossy(&output.stderr).trim()
            ));
        }

        let mut symbols: Vec<String> = String::from_utf8_lossy(&output.stdout)
            .lines()
            .filter_map(|line| line.split_whitespace().last())
            .map(|symbol| {
                #[cfg(target_os = "macos")]
                {
                    symbol.strip_prefix('_').unwrap_or(symbol).to_string()
                }
                #[cfg(not(target_os = "macos"))]
                {
                    symbol.to_string()
                }
            })
            .collect();
        symbols.sort();
        Ok(symbols)
    }

    fn write_app_exports_file(path: &Path, symbols: &[String]) -> Result<()> {
        #[cfg(target_os = "macos")]
        let contents = symbols
            .iter()
            .map(|symbol| format!("_{symbol}\n"))
            .collect::<String>();
        #[cfg(not(target_os = "macos"))]
        let contents = format!(
            "{{\n  global:\n{}  local: *;\n}};\n",
            symbols
                .iter()
                .map(|symbol| format!("    {symbol};\n"))
                .collect::<String>()
        );
        std::fs::write(path, contents)
            .with_context(|| format!("writing app export allowlist {:?}", path))
    }

    /// Recursively collect local compiler inputs under a deployment. This
    /// includes Perry/package/TypeScript configuration and package-manager
    /// lockfiles, not only source extensions. Hidden build state, dependencies,
    /// migrations, and static assets have separate identity/snapshot paths.
    fn collect_source_files(dir: &Path, out: &mut Vec<PathBuf>) -> Result<()> {
        let entries = std::fs::read_dir(dir)
            .with_context(|| format!("reading source directory {}", dir.display()))?;
        for entry in entries {
            let entry =
                entry.with_context(|| format!("reading source entry in {}", dir.display()))?;
            let path = entry.path();
            let name = entry.file_name();
            let name_str = name.to_str().unwrap_or("");
            let file_type = entry
                .file_type()
                .with_context(|| format!("reading source type {}", path.display()))?;
            if name_str.starts_with('.')
                || name_str == "node_modules"
                || name_str == "migrations"
                || name_str == "static"
                // Coop parses and canonically serializes this file into the
                // identity above. Copying/hashing its raw spelling as a Perry
                // input would make static-only config edits invalidate the
                // compiled-code cache even though Perry never reads it.
                || name_str == "coop.toml"
            {
                continue;
            }
            if file_type.is_symlink() {
                return Err(anyhow!(
                    "deployment source may not contain symlinks: {}",
                    path.display()
                ));
            }
            if file_type.is_dir() {
                Self::collect_source_files(&path, out)?;
            } else if file_type.is_file()
                && path
                    .extension()
                    .and_then(|extension| extension.to_str())
                    .is_some_and(|extension| {
                        matches!(
                            extension,
                            "ts" | "tsx"
                                | "js"
                                | "mjs"
                                | "cjs"
                                | "json"
                                | "toml"
                                | "yaml"
                                | "yml"
                                | "lock"
                                | "lockb"
                        )
                    })
            {
                out.push(path);
            }
        }
        Ok(())
    }

    async fn stop_background_generation(
        deployment: &str,
        max_wall_clock_ms: u32,
        stop: CancellationToken,
        tasks: &mut Vec<tokio::task::JoinHandle<()>>,
    ) {
        stop.cancel();
        let grace = Duration::from_millis(u64::from(max_wall_clock_ms))
            .saturating_add(Duration::from_secs(5));
        for mut task in tasks.drain(..) {
            if tokio::time::timeout(grace, &mut task).await.is_err() {
                warn!(
                    deployment,
                    grace_ms = grace.as_millis(),
                    "background task exceeded generation drain grace; aborting task"
                );
                task.abort();
                let _ = task.await;
            }
        }
    }

    async fn stop_background_tasks(&self, live: &mut LiveDeployment) {
        Self::stop_background_generation(
            &live.name,
            live.config.limits.max_wall_clock_ms,
            live.background_stop.clone(),
            &mut live.background_tasks,
        )
        .await;
    }

    async fn drain_live_deployment(&self, mut live: LiveDeployment) {
        info!(deployment = %live.name, "draining previous application runtime");
        self.stop_background_tasks(&mut live).await;
        let deployment_context_id = live.deployment_context_id;
        match live.runtime {
            LiveRuntime::InProcess { host } => {
                match tokio::time::timeout(Duration::from_secs(15), host.shutdown()).await {
                    Ok(Ok(())) => {}
                    Ok(Err(error)) => {
                        warn!(deployment = %live.name, ?error, "application executor shutdown failed");
                    }
                    Err(_) => {
                        warn!(
                            deployment = %live.name,
                            "application executor exceeded the 15 second drain grace; in-process native code cannot be forcibly cancelled"
                        );
                    }
                }
            }
            LiveRuntime::Worker {
                socket_path,
                mut child,
                client,
                cgroup,
                ..
            } => {
                let mut requires_kill = client.is_poisoned();
                if !requires_kill && client.shutdown(Duration::from_secs(10)).await.is_err() {
                    requires_kill = true;
                }
                if requires_kill {
                    warn!(
                        deployment = %live.name,
                        "poisoned worker cannot drain safely; sending SIGKILL"
                    );
                    let _ = child.kill().await;
                    let _ = child.wait().await;
                } else {
                    let kill_deadline = std::time::Instant::now() + Duration::from_secs(15);
                    loop {
                        if let Ok(Some(_)) = child.try_wait() {
                            break;
                        }
                        if std::time::Instant::now() > kill_deadline {
                            warn!(
                                deployment = %live.name,
                                "worker did not exit within grace period, sending SIGKILL"
                            );
                            let _ = child.kill().await;
                            let _ = child.wait().await;
                            break;
                        }
                        tokio::time::sleep(Duration::from_millis(50)).await;
                    }
                }
                let _ = std::fs::remove_file(socket_path);
                drop(cgroup);
            }
            LiveRuntime::Shard {
                runtime_id,
                client,
                process,
            } => {
                if let Err(error) = client.unload_shard_runtime(Duration::from_secs(15)).await {
                    warn!(
                        deployment = %live.name,
                        shard_slot = process.slot,
                        shard_generation = process.generation,
                        runtime_id,
                        ?error,
                        "shard application did not drain; terminating its failure domain"
                    );
                    process.terminate().await;
                }
                process.release(&live.name);
            }
        }
        unregister_enqueue_context(deployment_context_id);
    }

    async fn schedule_worker_restart(
        self: &Arc<Self>,
        deployment: &str,
        failed_client: Arc<WorkerClient>,
        reason: &'static str,
    ) {
        // `failed_client` remains owned by this restart task, so its allocation
        // address cannot be reused while the key is present.
        let restart_key = (deployment.to_string(), Arc::as_ptr(&failed_client) as usize);
        {
            let mut restarting = self.worker_restarts.lock().await;
            if !restarting.insert(restart_key.clone()) {
                return;
            }
        }

        let prior_failures = self
            .worker_restart_failures
            .lock()
            .await
            .get(deployment)
            .copied()
            .unwrap_or(0);
        let backoff = Self::worker_restart_backoff(prior_failures);
        crate::metrics::set_worker_restart_backoff(deployment, backoff.as_secs_f64());

        let supervisor = self.clone();
        let deployment = deployment.to_string();
        tokio::spawn(async move {
            if !backoff.is_zero() {
                tokio::time::sleep(backoff).await;
            }
            let still_current = {
                let live = supervisor.live.read().await;
                match live.get(&deployment).map(|live| &live.runtime) {
                    Some(LiveRuntime::Worker { client, .. })
                    | Some(LiveRuntime::Shard { client, .. }) => {
                        Arc::ptr_eq(client, &failed_client) && client.is_poisoned()
                    }
                    _ => false,
                }
            };
            if still_current {
                warn!(deployment = %deployment, reason, "replacing poisoned worker generation");
                match supervisor.load_deployment(&deployment).await {
                    Ok(()) => {
                        supervisor
                            .worker_restart_failures
                            .lock()
                            .await
                            .remove(&deployment);
                        crate::metrics::set_worker_restart_backoff(&deployment, 0.0);
                        crate::metrics::record_worker_restart(&deployment, reason, "success");
                    }
                    Err(error) => {
                        let mut failures = supervisor.worker_restart_failures.lock().await;
                        let count = failures.entry(deployment.clone()).or_default();
                        *count = count.saturating_add(1).min(16);
                        crate::metrics::record_worker_restart(&deployment, reason, "failure");
                        error!(deployment = %deployment, reason, ?error, "poisoned worker replacement failed");
                    }
                }
            }
            supervisor.worker_restarts.lock().await.remove(&restart_key);
        });
    }

    fn worker_restart_backoff(prior_failures: u32) -> Duration {
        if prior_failures == 0 {
            Duration::ZERO
        } else {
            Duration::from_secs(1_u64 << prior_failures.saturating_sub(1).min(6))
        }
    }

    /// Rebuild the router state from the current `live` map.
    async fn rebuild_router_state(&self) {
        let live = self.live.read().await;
        let routes: Vec<DeploymentRoutes> = live
            .values()
            .map(|d| DeploymentRoutes::from_config(&d.config, d.deployment_dir.clone()))
            .collect();

        let new_state = Arc::new(RouterState::build(routes));
        self.router_state.store(new_state.clone());
        crate::metrics::set_deployment_count(new_state.deployment_count());

        info!(
            deployments = new_state.deployment_count(),
            "router state rebuilt"
        );
    }

    /// Read a process's RSS in KiB from /proc/<pid>/status (Linux only).
    #[cfg(target_os = "linux")]
    fn read_rss_kib(pid: u32) -> Option<u64> {
        let path = format!("/proc/{}/status", pid);
        let content = std::fs::read_to_string(&path).ok()?;
        for line in content.lines() {
            if let Some(rest) = line.strip_prefix("VmRSS:") {
                let n: u64 = rest.trim().split_whitespace().next()?.parse().ok()?;
                return Some(n);
            }
        }
        None
    }

    #[cfg(not(target_os = "linux"))]
    #[allow(dead_code)]
    fn read_rss_kib(_pid: u32) -> Option<u64> {
        None
    }

    fn read_rss_mb(pid: u32) -> Option<u64> {
        Self::read_rss_kib(pid).map(|kib| kib / 1024)
    }

    /// Background task that periodically checks each worker's RSS and
    /// restarts any worker that exceeds its `max_worker_rss_mb` limit.
    /// Bounded the impact of ballooning deployments (e.g. one that
    /// builds large response buffers).
    pub fn spawn_rss_watchdog(self: Arc<Self>) -> tokio::task::JoinHandle<()> {
        tokio::spawn(async move {
            // Poisoned transports need prompt replacement; RSS sampling is
            // intentionally slower because walking every worker process once
            // per second would add needless steady-state work.
            let mut interval = tokio::time::interval(Duration::from_secs(1));
            let mut tick = 0_u64;
            loop {
                interval.tick().await;
                let sample_rss = tick % 30 == 0;
                tick = tick.wrapping_add(1);
                if let Some(store) = self.queue_store.as_ref() {
                    crate::metrics::set_queue_pool_status(&store.pool_status());
                }
                let arena_hosts = {
                    let live = self.live.read().await;
                    let mut hosts = Vec::new();
                    for (name, deployment) in live.iter() {
                        if let LiveRuntime::InProcess { host } = &deployment.runtime {
                            crate::metrics::set_executor_queue(
                                name,
                                host.queue_depth(),
                                host.queue_capacity(),
                            );
                            if sample_rss {
                                hosts.push((name.clone(), host.clone()));
                            }
                        }
                    }
                    hosts
                };
                for (name, host) in arena_hosts {
                    match host.memory_stats().await {
                        Ok(memory) => {
                            crate::metrics::set_application_arena(
                                &name,
                                memory.arena_live_bytes,
                                memory.arena_reserved_bytes,
                            );
                        }
                        Err(error) => {
                            warn!(deployment = %name, ?error, "querying Perry arena metrics failed")
                        }
                    }
                }
                let to_restart: Vec<(
                    String,
                    u32,
                    Option<u64>,
                    u32,
                    Arc<WorkerClient>,
                    &'static str,
                )> = {
                    // `Child::try_wait` is the authoritative cross-platform
                    // liveness check and reaps an idle crashed worker. It
                    // requires mutable access, so take the map write lock only
                    // for this bounded, non-awaiting scan.
                    let mut live = self.live.write().await;
                    live.iter_mut()
                        .filter_map(|(name, d)| {
                            let limit = d.config.limits.max_worker_rss_mb;
                            let LiveRuntime::Worker {
                                pid,
                                child,
                                client,
                                cgroup,
                                ..
                            } = &mut d.runtime
                            else {
                                return None;
                            };
                            let cgroup_stats = cgroup.as_ref().map(WorkerCgroup::stats);
                            if sample_rss {
                                if let Some(stats) = cgroup_stats.as_ref() {
                                    crate::metrics::set_worker_cgroup_stats(name, stats);
                                }
                            }
                            let rss = (sample_rss && cgroup.is_none())
                                .then(|| Self::read_rss_mb(*pid))
                                .flatten();
                            let exited = match child.try_wait() {
                                Ok(status) => status,
                                Err(error) => {
                                    warn!(deployment = %name, ?error, "checking worker process status failed");
                                    client.mark_poisoned(
                                        WorkerPoisonCause::StatusCheck,
                                        "worker process status check failed",
                                    );
                                    return Some((
                                        name.clone(),
                                        *pid,
                                        rss,
                                        limit,
                                        client.clone(),
                                        "status_error",
                                    ));
                                }
                            };
                            let reason = if exited.is_some() {
                                client.mark_poisoned(
                                    WorkerPoisonCause::ProcessExit,
                                    "worker process exited",
                                );
                                Some(
                                    if cgroup_stats
                                        .as_ref()
                                        .and_then(|stats| stats.memory_oom_kill_events)
                                        .is_some_and(|events| events > 0)
                                    {
                                        "cgroup_oom"
                                    } else {
                                        "exit"
                                    },
                                )
                            } else if rss.is_some_and(|rss| rss > limit as u64) {
                                Some("rss_limit")
                            } else if client.is_poisoned() {
                                Some("transport")
                            } else {
                                None
                            }?;
                            Some((name.clone(), *pid, rss, limit, client.clone(), reason))
                        })
                        .collect()
                };
                for (name, pid, rss, limit, client, reason) in to_restart {
                    if rss.is_some_and(|rss| rss > limit as u64) {
                        warn!(
                            deployment = %name,
                            pid,
                            rss_mb = rss,
                            limit_mb = limit,
                            "worker RSS exceeded limit, scheduling replacement"
                        );
                        client.mark_poisoned(
                            WorkerPoisonCause::RssLimit,
                            "worker RSS exceeded configured limit",
                        );
                    }
                    self.schedule_worker_restart(&name, client, reason).await;
                }

                let shard_groups = {
                    let live = self.live.read().await;
                    let mut groups: HashMap<
                        (usize, u64),
                        (Arc<ShardProcess>, Vec<(String, Arc<WorkerClient>)>),
                    > = HashMap::new();
                    for (name, deployment) in live.iter() {
                        if let LiveRuntime::Shard {
                            process, client, ..
                        } = &deployment.runtime
                        {
                            groups
                                .entry((process.slot, process.generation))
                                .or_insert_with(|| (process.clone(), Vec::new()))
                                .1
                                .push((name.clone(), client.clone()));
                        }
                    }
                    groups.into_values().collect::<Vec<_>>()
                };
                for (process, deployments) in shard_groups {
                    let cgroup_stats = process.cgroup_stats();
                    if sample_rss {
                        if let Some(stats) = cgroup_stats.as_ref() {
                            for (name, _) in &deployments {
                                crate::metrics::set_worker_cgroup_stats(name, stats);
                            }
                        }
                    }
                    let rss = (sample_rss && process.cgroup.is_none())
                        .then(|| Self::read_rss_mb(process.pid))
                        .flatten();
                    let status = process.child.lock().await.try_wait();
                    let reason = match status {
                        Err(error) => {
                            warn!(
                                shard_slot = process.slot,
                                shard_generation = process.generation,
                                ?error,
                                "checking worker shard status failed"
                            );
                            Some("status_error")
                        }
                        Ok(Some(_)) => Some(
                            if cgroup_stats
                                .as_ref()
                                .and_then(|stats| stats.memory_oom_kill_events)
                                .is_some_and(|events| events > 0)
                            {
                                "cgroup_oom"
                            } else {
                                "exit"
                            },
                        ),
                        Ok(None)
                            if rss.is_some_and(|rss| {
                                rss > u64::from(self.runtime_cfg.execution.shards.max_rss_mb)
                            }) =>
                        {
                            Some("rss_limit")
                        }
                        Ok(None) if process.is_poisoned() => Some("failure_domain"),
                        Ok(None) if deployments.iter().any(|(_, client)| client.is_poisoned()) => {
                            Some("transport")
                        }
                        Ok(None) => None,
                    };
                    let Some(reason) = reason else {
                        continue;
                    };

                    if process.mark_poisoned() {
                        crate::metrics::record_shard_failure(process.slot, reason);
                    }
                    for (_, client) in &deployments {
                        client.mark_poisoned(
                            WorkerPoisonCause::ShardDomain,
                            "worker shard failure requires domain replacement",
                        );
                    }
                    if rss.is_some_and(|rss| {
                        rss > u64::from(self.runtime_cfg.execution.shards.max_rss_mb)
                    }) {
                        warn!(
                            shard_slot = process.slot,
                            shard_generation = process.generation,
                            pid = process.pid,
                            rss_mb = rss,
                            limit_mb = self.runtime_cfg.execution.shards.max_rss_mb,
                            "worker shard RSS exceeded aggregate limit"
                        );
                    }
                    process.terminate().await;
                    for (name, client) in deployments {
                        self.schedule_worker_restart(&name, client, reason).await;
                    }
                }
            }
        })
    }

    /// Remove a deployment entirely (directory deleted, or explicit
    /// admin action). Drains the worker, tears down the Bunny Pull Zone,
    /// and rebuilds router state.
    pub async fn remove_deployment(&self, name: &str) {
        let operation = self.deployment_operation(name).await;
        let _operation_guard = operation.lock_owned().await;
        let old = {
            let mut live = self.live.write().await;
            live.remove(name)
        };
        if let Some(live) = old {
            self.drain_live_deployment(live).await;
        }
        crate::metrics::set_deployment_isolation(name, false, false);
        crate::metrics::set_deployment_shard(name, None);

        // Bunny CDN: tear down the Pull Zone.
        if let Some(bunny_cfg) = &self.runtime_cfg.cdn.bunny {
            if let Err(e) = cdn::teardown_deployment(bunny_cfg, name).await {
                warn!(
                    deployment = %name,
                    error = ?e,
                    "failed to tear down Bunny Pull Zone"
                );
            }
        }

        self.rebuild_router_state().await;
    }
