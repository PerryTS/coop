#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum CronTickDecision {
    Dispatch,
    SkipLate,
    SkipOverlap,
}

fn cron_tick_decision(
    overlap: CronOverlapPolicy,
    late: CronLatePolicy,
    max_lateness_ms: u64,
    lateness_ms: u64,
    in_flight: bool,
) -> CronTickDecision {
    if lateness_ms > max_lateness_ms && late == CronLatePolicy::Skip {
        CronTickDecision::SkipLate
    } else if in_flight && overlap == CronOverlapPolicy::Skip {
        CronTickDecision::SkipOverlap
    } else {
        CronTickDecision::Dispatch
    }
}

