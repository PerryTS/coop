#[derive(Default)]
struct ShardReservations {
    /// Deployment name -> overlapping loaded generation count.
    generations: HashMap<String, usize>,
}

impl ShardReservations {
    /// Reserve one runtime generation. Returns `false` only when this would
    /// add a new logical deployment beyond the shard's distinct-app limit.
    fn reserve(&mut self, deployment: &str, max_apps: usize) -> bool {
        if let Some(generations) = self.generations.get_mut(deployment) {
            *generations = generations.saturating_add(1);
            return true;
        }
        if self.generations.len() >= max_apps {
            return false;
        }
        self.generations.insert(deployment.to_string(), 1);
        true
    }

    fn release(&mut self, deployment: &str) {
        if let Some(generations) = self.generations.get_mut(deployment) {
            if *generations > 1 {
                *generations -= 1;
            } else {
                self.generations.remove(deployment);
            }
        }
    }

    fn contains(&self, deployment: &str) -> bool {
        self.generations.contains_key(deployment)
    }

    fn resident_deployments(&self) -> usize {
        self.generations.len()
    }

    #[cfg(test)]
    fn generation_count(&self, deployment: &str) -> usize {
        self.generations.get(deployment).copied().unwrap_or(0)
    }
}

pub(crate) struct ShardProcess {
    slot: usize,
    generation: u64,
    socket_path: PathBuf,
    child: TokioMutex<Child>,
    pid: u32,
    cgroup: Option<WorkerCgroup>,
    poisoned: AtomicBool,
    reservations: StdMutex<ShardReservations>,
}

impl ShardProcess {
    /// Returns `false` when the shard is at its distinct-application capacity.
    /// Replacement generations of an already resident deployment still fit.
    fn reserve(&self, deployment: &str, max_apps: usize) -> Result<bool> {
        let mut reservations = self
            .reservations
            .lock()
            .map_err(|_| anyhow!("worker shard reservation lock poisoned"))?;
        let reserved = reservations.reserve(deployment, max_apps);
        crate::metrics::set_shard_resident_deployments(
            self.slot,
            reservations.resident_deployments(),
        );
        Ok(reserved)
    }

    fn release(&self, deployment: &str) {
        let Ok(mut reservations) = self.reservations.lock() else {
            return;
        };
        reservations.release(deployment);
        crate::metrics::set_shard_resident_deployments(
            self.slot,
            reservations.resident_deployments(),
        );
    }

    fn contains(&self, deployment: &str) -> bool {
        self.reservations
            .lock()
            .is_ok_and(|reservations| reservations.contains(deployment))
    }

    /// Returns true only for the caller that first poisoned this failure
    /// domain, allowing failure metrics to remain one-per-domain event.
    fn mark_poisoned(&self) -> bool {
        !self.poisoned.swap(true, Ordering::AcqRel)
    }

    fn is_poisoned(&self) -> bool {
        self.poisoned.load(Ordering::Acquire)
    }

    fn cgroup_stats(&self) -> Option<WorkerCgroupStats> {
        self.cgroup.as_ref().map(WorkerCgroup::stats)
    }

    async fn terminate(&self) {
        let _ = self.mark_poisoned();
        let mut child = self.child.lock().await;
        match child.try_wait() {
            Ok(Some(_)) => {}
            Ok(None) | Err(_) => {
                let _ = child.kill().await;
                let _ = child.wait().await;
            }
        }
        let _ = std::fs::remove_file(&self.socket_path);
    }
}

pub enum LiveRuntime {
    /// Zero-transport-latency mode: the dylib is already initialized in the
    /// daemon and every invocation is sent directly to its pinned thread.
    InProcess { host: Arc<DeploymentHost> },
    /// Process-isolation mode: a dedicated process owns the library.
    Worker {
        socket_path: PathBuf,
        child: tokio::process::Child,
        pid: u32,
        client: Arc<WorkerClient>,
        cgroup: Option<WorkerCgroup>,
    },
    /// Process-sharded mode: several independently addressed application
    /// executors share one supervised worker process and cgroup.
    Shard {
        runtime_id: String,
        client: Arc<WorkerClient>,
        process: Arc<ShardProcess>,
    },
}

impl LiveRuntime {
    const fn execution_mode(&self) -> ExecutionMode {
        match self {
            Self::InProcess { .. } => ExecutionMode::InProcess,
            Self::Worker { .. } => ExecutionMode::Worker,
            Self::Shard { .. } => ExecutionMode::Shard,
        }
    }
}

#[derive(Clone)]
enum RuntimeDispatchTarget {
    InProcess(Arc<DeploymentHost>),
    Worker(Arc<WorkerClient>),
}

impl RuntimeDispatchTarget {
    fn from_runtime(runtime: &LiveRuntime) -> Self {
        match runtime {
            LiveRuntime::InProcess { host } => Self::InProcess(host.clone()),
            LiveRuntime::Worker { client, .. } => Self::Worker(client.clone()),
            LiveRuntime::Shard { client, .. } => Self::Worker(client.clone()),
        }
    }

    fn worker_client(&self) -> Option<Arc<WorkerClient>> {
        match self {
            Self::InProcess(_) => None,
            Self::Worker(client) => Some(client.clone()),
        }
    }

    fn requires_replacement(&self) -> bool {
        self.worker_client()
            .is_some_and(|client| client.is_poisoned())
    }

    async fn dispatch_http(&self, request: HttpDispatchRequest) -> Result<HttpDispatchResponse> {
        match self {
            Self::InProcess(host) => host.dispatch_http(request).await,
            Self::Worker(client) => {
                use base64::Engine;
                let socket_request = DeploymentRequest {
                    method: request.method,
                    path: request.path,
                    query: request.query,
                    headers: request.headers.into_iter().collect(),
                    remote_addr: request.remote_addr,
                    scheme: request.scheme,
                    host: request.host,
                    body_base64: base64::engine::general_purpose::STANDARD.encode(request.body),
                };
                let response = client.dispatch(socket_request).await?;
                Ok(HttpDispatchResponse {
                    status: response.status,
                    headers: response.headers.into_iter().collect(),
                    body: base64::engine::general_purpose::STANDARD
                        .decode(response.body_base64)
                        .context("worker returned an invalid Base64 HTTP body")?,
                })
            }
        }
    }

    async fn fire_cron(&self, context: coop_host_abi::CronContext) -> Result<()> {
        match self {
            Self::InProcess(host) => host.fire_cron(context).await,
            Self::Worker(client) => client.fire_cron(context).await,
        }
    }

    async fn deliver_queue(
        &self,
        message: coop_host_abi::QueueDispatchMessage,
    ) -> Result<coop_host_abi::QueueDisposition> {
        match self {
            Self::InProcess(host) => host.deliver_queue(message).await,
            Self::Worker(client) => {
                use base64::Engine;
                client
                    .deliver_queue(coop_host_abi::QueueMessage {
                        queue_name: message.queue_name,
                        message_id: message.message_id,
                        attempt: message.attempt,
                        max_retries: message.max_retries,
                        payload_base64: base64::engine::general_purpose::STANDARD
                            .encode(message.payload),
                    })
                    .await
            }
        }
    }
}

#[derive(Clone)]
struct DeploymentInvocationTarget {
    runtime: RuntimeDispatchTarget,
    admission: Arc<InvocationAdmission>,
}

impl DeploymentInvocationTarget {
    fn from_live(live: &LiveDeployment) -> Self {
        Self {
            runtime: RuntimeDispatchTarget::from_runtime(&live.runtime),
            admission: live.admission.clone(),
        }
    }

    fn new(runtime: &LiveRuntime, admission: Arc<InvocationAdmission>) -> Self {
        Self {
            runtime: RuntimeDispatchTarget::from_runtime(runtime),
            admission,
        }
    }

    fn worker_client(&self) -> Option<Arc<WorkerClient>> {
        self.runtime.worker_client()
    }

    async fn dispatch_http(
        &self,
        request: HttpDispatchRequest,
    ) -> Result<HttpDispatchResponse, InvocationError> {
        self.admission.validate_http_request(&request)?;
        let runtime = self.runtime.clone();
        let result = self
            .admission
            .invoke("http", async move { runtime.dispatch_http(request).await })
            .await;
        self.poison_timed_out_worker(&result, "HTTP invocation deadline exceeded");
        let response = result?;
        self.admission.validate_http_response(&response)?;
        Ok(response)
    }

    async fn fire_cron(&self, context: coop_host_abi::CronContext) -> Result<(), InvocationError> {
        let runtime = self.runtime.clone();
        let result = self
            .admission
            .invoke("cron", async move { runtime.fire_cron(context).await })
            .await;
        self.poison_timed_out_worker(&result, "cron invocation deadline exceeded");
        result
    }

    async fn deliver_queue(
        &self,
        message: coop_host_abi::QueueDispatchMessage,
    ) -> Result<coop_host_abi::QueueDisposition, InvocationError> {
        self.admission.validate_queue_message(&message)?;
        let runtime = self.runtime.clone();
        let result = self
            .admission
            .invoke("queue", async move { runtime.deliver_queue(message).await })
            .await;
        self.poison_timed_out_worker(&result, "queue invocation deadline exceeded");
        result
    }

    /// Reserve deployment capacity before claiming a durable row. This keeps
    /// overload from consuming a lease or delivery attempt.
    fn try_admit_queue(&self) -> Result<InvocationPermit, InvocationError> {
        self.admission.try_admit("queue", false)
    }

    async fn deliver_admitted_queue(
        &self,
        message: coop_host_abi::QueueDispatchMessage,
        permit: InvocationPermit,
    ) -> Result<coop_host_abi::QueueDisposition, InvocationError> {
        self.admission.validate_queue_message(&message)?;
        let runtime = self.runtime.clone();
        let result = self
            .admission
            .invoke_admitted("queue", permit, async move {
                runtime.deliver_queue(message).await
            })
            .await;
        self.poison_timed_out_worker(&result, "queue invocation deadline exceeded");
        result
    }

    fn poison_timed_out_worker<T>(&self, result: &Result<T, InvocationError>, reason: &str) {
        if matches!(result, Err(InvocationError::DeadlineExceeded { .. })) {
            if let Some(client) = self.runtime.worker_client() {
                client.mark_poisoned(WorkerPoisonCause::Deadline, reason);
            }
        }
    }
}

