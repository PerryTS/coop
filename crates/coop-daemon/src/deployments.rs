/// Debug-build-only process crash barrier used by the real daemon SIGKILL
/// matrix. Release binaries contain no environment-controlled pause path.
#[cfg(debug_assertions)]
async fn test_pause_at_process_crash_point(point: &str, deployment: &str, child_pid: Option<u32>) {
    if std::env::var("COOP_TEST_PROCESS_CRASH_POINT").as_deref() != Ok(point) {
        return;
    }
    if std::env::var("COOP_TEST_PROCESS_CRASH_DEPLOYMENT")
        .ok()
        .is_some_and(|expected| expected != deployment)
    {
        return;
    }
    let Some(marker) = std::env::var_os("COOP_TEST_PROCESS_CRASH_MARKER") else {
        return;
    };
    if std::env::var_os("COOP_TEST_PROCESS_CRASH_ARM")
        .is_some_and(|arm| !PathBuf::from(arm).exists())
    {
        return;
    }
    let marker = PathBuf::from(marker);
    let contents = format!(
        "point={point}\ndeployment={deployment}\ndaemon_pid={}\nchild_pid={}\n",
        std::process::id(),
        child_pid.map_or_else(String::new, |pid| pid.to_string())
    );
    std::fs::write(&marker, contents).expect("writing process crash-test marker");
    std::fs::File::open(&marker)
        .and_then(|file| file.sync_all())
        .expect("syncing process crash-test marker");
    info!(deployment, point, "paused at process crash-test boundary");
    std::future::pending::<()>().await;
}

